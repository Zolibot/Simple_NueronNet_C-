#pragma once

#include <vector>
#include <random>
#include <cmath>

class NeuralNetController;

// ============================================================================
// Neuron — минимальная структура одного нейрона
// ============================================================================
//
// Почему именно три поля (output, error, z), а не, скажем, одно output?
//
//  output — результат работы функции активации для данного нейрона.
//           Именно это значение «течёт вперёд» по сети при прямом проходе
//           и используется при вычислении ошибки следующего слоя.
//
//  error  — локальный градиент (частная производная функции потерь по
//           взвешенной сумме z данного нейрона). Вычисляется при обратном
//           распространении и используется для обновления весов, ведущих
//           к этому нейрону.
//
//  z      — «сырая» взвешенная сумма входов (sum w_i * x_i + bias) ДО
//           применения функции активации. Это поле необходимо для:
//             • Batch Normalization — нормализация применяется к z, а не к output;
//             • производных некоторых функций активации (ReLU, Leaky ReLU, Tanh)
//               требуют именно pre-activation значение;
//             • отладки и инспекции промежуточных значений.
//
// Почему Layer — это vector<Neuron>, а не vector<vector<float>>?
//
//  vector<vector<float>> хранил бы только числа и терял семантику.
//  Структура Neuron явно разделяет три разных по смыслу величины,
//  которые живут на каждом нейроне. Это даёт:
//     • самодокументируемость кода (neuron.output vs neuron.error);
//     • безопасность типов — нельзя случайно перепутать ошибку с выходом;
//     • возможность в будущем добавить поля без изменения сигнатур функций.
//
struct Neuron {
    float output;  // Результат после функции активации; передаётся следующему слою
    float error;   // Локальный градиент (dLoss/dz); используется при обратном распространении
    float z;       // Взвешенная сумма входов до активации; нужна для BatchNorm и некоторых производных
};

// ============================================================================
// Layer — слой нейронов
// ============================================================================
//
// Слой — это упорядоченный набор нейронов. Каждый слой может быть входным,
// скрытым или выходным. Размер вектора равен количеству нейронов в слое.
//
using Layer = std::vector<Neuron>;

// ============================================================================
// WeightMatrix — матрица весов между двумя слоями
// ============================================================================
//
// Индексация: weN[выходящий_нейрон][входящий_нейрон]
//
// То есть weN[j][i] — вес связи от i-го нейрона предыдущего слоя к j-му
// нейрону текущего слоя. Такая раскладка удобна при прямом проходе:
//
//   z_j = sum_i(weN[j][i] * input[i]) + bias[j]
//
// что соответствует обычному матричному умножению W * x.
//
// Почему vector<vector<float>>, а не плоский vector<float>?
//   • Двумерная структура естественным образом отражает математику слоёв;
//   • Упрощает код — не нужно вручную вычислять смещения индексов;
//   • Потеря производительности минимальна (аллокации происходят один раз
//     при создании сети, а не на каждом шаге обучения).
//
using WeightMatrix = std::vector<std::vector<float>>;

// ============================================================================
// WeightInit — стратегия инициализации весов
// ============================================================================
//
// Правильная инициализация критически важна для скорости сходимости сети.
// Плохие начальные веса приводят к затухающим или взрывающимся градиентам.
//
// INIT_UNIFORM — равномерное распределение в диапазоне [-weightRange, +weightRange].
//                Простейший метод, исторический. Не масштабируется с размером
//                слоя, поэтому подходит только для маленьких сетей.
//
// INIT_XAVIER (Glorot) — равномерное или нормальное распределение с дисперсией
//                        2 / (n_in + n_out). Оптимально для сигмоиды и Tanh,
//                        потому что сохраняет дисперсию активаций и градиентов
//                        на обоих направлениях (вперёд и назад).
//
// INIT_HE (Kaiming) — дисперсия 2 / n_in. Разработан специально для ReLU и
//                     его модификаций, потому что ReLU «обнуляет» примерно
//                     половину входов, и HE-инициализация это компенсирует.
//                     Также хорошо работает с Leaky ReLU.
//
enum WeightInit { INIT_UNIFORM, INIT_XAVIER, INIT_HE };

// ============================================================================
// ActivationType — тип функции активации
// ============================================================================
//
// Функция активации вносит нелинейность, без чего сеть была бы эквивалентна
// одному линейному преобразованию, независимо от количества слоёв.
//
// ACTIVATION_SIGMOID — классическая S-образная функция, сжимающая вход в (0, 1).
//                      Исторически первая, удобна для бинарной классификации.
//                      Недостатки: насыщается (градиент ≈ 0) при больших |x|,
//                      что замедляет обучение; выход не центрирован вокруг нуля.
//
// ACTIVATION_RELU — Rectified Linear Unit: max(0, x). Самая популярная функция
//                   для скрытых слоёв. Не насыщается при положительных x,
//                   вычислительно дешёвая. Проблема: «мёртвые нейроны» — если
//                   нейрон ушёл в отрицательную область, градиент навсегда
//                   станет нулевым.
//
// ACTIVATION_LEAKY_RELU — вариант ReLU: для x < 0 возвращает 0.01 * x.
//                         Решает проблему «мёртвых нейронов», позволяя
//                         маленькому градиенту протекать даже при отрицательных
//                         значениях. Коэффициент наклона (0.01) — эмпирический.
//
// ACTIVATION_TANH — гиперболический тангенс, сжимает вход в (-1, 1).
//                   Центрирован вокруг нуля, что ускоряет обучение по сравнению
//                   с сигмоидой. Но также подвержен насыщению.
//
enum ActivationType { ACTIVATION_SIGMOID, ACTIVATION_RELU, ACTIVATION_LEAKY_RELU, ACTIVATION_TANH };

// ============================================================================
// OptimizerType — алгоритм оптимизации (обновления весов)
// ============================================================================
//
// Оптимизатор определяет, как именно градиент преобразуется в изменение весов.
//
// OPTIMIZER_SGD — стохастический градиентный спуск: w -= lr * gradient.
//                 Простейший метод. Работает, но может осциллировать и медленно
//                 сходиться в «оврагах» ландшафта функции потерь.
//
// OPTIMIZER_ADAM — адаптивная оценка моментов (Mean + RMSProp). Поддерживает
//                  скользящее среднее градиента (m) и скользящее среднее
//                  квадрата градиента (v), с коррекцией смещения. Обычно
//                  сходится быстрее SGD и требует меньше подстройки гиперпараметров.
//
// OPTIMIZER_MOMENTUM — SGD с импульсом: накапливает экспоненциально убывающую
//                      сумму прошлых градиентов. Помогает «разогнаться» через
//                      плоские области и сглаживает осцилляции. Параметр
//                      momentum (обычно 0.9) определяет «память» оптимизатора.
//
enum OptimizerType { OPTIMIZER_SGD, OPTIMIZER_ADAM, OPTIMIZER_MOMENTUM };

// ============================================================================
// NeuralNet — ядро нейронной сети (stateless utility-класс)
// ============================================================================
//
// Этот класс инкапсулирует все низкоуровневые операции:
//   • прямой проход (forward);
//   • обратный проход (backward / reverse);
//   • инициализацию весов;
//   • функции активации и их производные;
//   • поддержку dropout и batch normalization.
//
// «Stateless» означает, что сам класс не хранит архитектуру сети — он лишь
// выполняет операции над структурами (Layer, WeightMatrix), которые передаются
// ему из NeuralNetController. Это разделение позволяет:
//   • переиспользовать один экземпляр NeuralNet для нескольких сетей;
//   • тестировать отдельные функции независимо;
//   • избегать циклических зависимостей.
//
// Поле timestep_ объявлено как mutable, потому что оно изменяется внутри
// константных методов (в частности, при вызовах Adam), что нарушает обычную
// семантику const-correctness, но оправдано тем, что timestep — это
// внутреннее состояние RNG-подобного механизма, а не логическое состояние
// объекта.
//
class NeuralNet {
private:
    // Генератор псевдослучайных чисел, используемый для инициализации весов
    // и dropout-масок. Объявлен как mutable, чтобы можно было генерировать
    // случайные числа даже в const-контекстах.
    mutable std::default_random_engine rng_;

public:
    int timestep_ = 0;          // Глобальный счётчик шагов для Adam-оптимизатора (bias correction)
    float weightRange = 0.5f;   // Диапазон равномерной инициализации [-weightRange, +weightRange]
    WeightInit defaultInit = INIT_HE;        // Инициализация по умолчанию (HE хорошо работает с ReLU)
    ActivationType activationType = ACTIVATION_SIGMOID;  // Функция активации по умолчанию
    OptimizerType optimizerType = OPTIMIZER_SGD;         // Оптимизатор по умолчанию
    float adamBeta1 = 0.9f;     // Коэффициент затухания для первого момента в Adam (скорость)
    float adamBeta2 = 0.999f;   // Коэффициент затухания для второго момента в Adam (накопление)
    float adamEpsilon = 1e-8f;  // Маленькое число в Adam для предотвращения деления на ноль
    float momentum = 0.9f;      // Коэффициент импульса для Momentum-оптимизатора
    bool useBatchNorm = false;  // Флаг включения Batch Normalization
    float dropoutRate = 0.0f;   // Вероятность «выключения» нейрона при dropout (0.0 — выключено)
    bool useDropout = false;    // Флаг включения Dropout (регуляризация)

    // Конструктор: инициализирует RNG случайным seed'ом.
    NeuralNet();

    // Генерирует случайное число в диапазоне [low, high] с использованием
    // внутреннего генератора rng_.
    float random(float low, float high);

    // ---- Функции активации и их производные (статические, pure functions) ----

    // Сигмоида: 1 / (1 + exp(-x)), выход в (0, 1)
    static float sigmoid(float x);
    // Производная сигмоиды, вычисленная через уже активированный выход:
    // sigmoid'(x) = output * (1 - output). Принимает activatedOutput, а не x,
    // потому что output уже вычислен при прямом проходе — экономия exp().
    static float sigmoidDerivative(float activatedOutput);

    // ReLU: max(0, x)
    static float relu(float x);
    // Производная ReLU: 1 если x > 0, иначе 0. Требует pre-activation значение x.
    static float reluDerivative(float x);

    // Leaky ReLU: x > 0 ? x : 0.01 * x
    static float leakyRelu(float x);
    // Производная Leaky ReLU: 1 если x > 0, иначе 0.01
    static float leakyReluDerivative(float x);

    // Tanh: гиперболический тангенс, выход в (-1, 1)
    static float tanhActivation(float x);
    // Производная Tanh через активированный выход: tanh'(x) = 1 - output^2
    static float tanhDerivative(float activatedOutput);

    // Универсальная функция активации — делегирует конкретному типу.
    static float activate(float x, ActivationType type);
    // Универсальная производная — принимает активированный выход и тип.
    // Для ReLU/Leaky ReLU параметр x интерпретируется как pre-activation,
    // для Sigmoid/Tanh — как post-activation (это историческая несогласованность
    // в API, но производные internally корректны).
    static float activateDerivative(float x, ActivationType type);

    // ---- Прямой проход ----

    // Классический прямой проход: для каждого нейрона выходного слоя вычисляет
    // z = sum(weights * inputs) + bias, затем применяет функцию активации.
    //
    // Параметры:
    //   inL             — входной слой (активации предыдущего слоя)
    //   weN             — матрица весов [выход][вход]
    //   ouL             — выходной слой (записываются результат)
    //   skipBiasIndex   — индекс нейрона, для которого НЕ добавляется bias
    //                     (используется при BatchNorm, где bias встроен в gamma/beta)
    void forwardPass(const Layer &inL, const WeightMatrix &weN, Layer &ouL, int skipBiasIndex = -1);

    // Прямой проход с Dropout: перед активацией случайно «зануляет» часть
    // нейронов согласно dropoutRate. Mask сохраняет информацию о том, какие
    // нейроны были активны, для корректного обратного прохода.
    //
    // Параметры:
    //   dropoutMask     — слой-маска: output = 1.0 если нейрон активен, 0.0 если выключен
    //   dropoutRate     — вероятность исключения нейрона
    //   Остальные — как у forwardPass
    void forwardPassWithDropout(const Layer &inL, const WeightMatrix &weN, Layer &ouL, Layer &dropoutMask, float dropoutRate, int skipBiasIndex = -1);

    // ---- Обратный проход (вычисление градиентов) ----

    // Обратный проход: для каждого нейрона входного слоя вычисляет ошибку
    // (градиент), «распределяя» ошибку выходного слоя через веса обратно.
    // Формула: error_in[i] = sum_j(error_out[j] * weight[j][i])
    //
    // Параметры:
    //   inL   — входной слой (нейроны, к которым нужно propagate error)
    //   weN   — матрица весов [выход][вход]
    //   ouL   — выходной слой (нейроны с уже вычисленной ошибкой)
    //   skipBiasIndex — индекс нейрона, ошибку которого не нужно считать (bias)
    void reversePass(const Layer &inL, const WeightMatrix &weN, Layer &ouL, int skipBiasIndex = -1);

    // ---- Инициализация весов ----

    // Заполняет матрицу весов случайными значениями согласно выбранной стратегии.
    //
    // Параметры:
    //   we   — матрица весов для инициализации
    //   init — стратегия (INIT_UNIFORM, INIT_XAVIER, INIT_HE)
    void randomizeWeights(WeightMatrix &we, WeightInit init = INIT_HE);

    // ---- Вычисление ошибки выходного слоя ----

    // Вычисляет градиент ошибки для нейронов выходного слоя на основе
    // разницы между предсказанием и целевым значением.
    // Формула: error[i] = (output[i] - target[i]) * activation_derivative(z[i])
    //
    // Параметры:
    //   inL    — входной слой (для вычисления производной активации)
    //   weN    — матрица весов (не используется в данной версии, оставлен для API)
    //   ouL    — выходной слой (записывается ошибка)
    //   outInL — входной слой следующего прохода (дублирует ouL для удобства)
    void computeError(const Layer &inL, const WeightMatrix &weN, const Layer &ouL, Layer &outInL);

    // Вариант computeError с учётом dropout-маски: ошибка умножается на маску,
    // чтобы «выключенные» нейроны не получали градиент.
    void computeErrorWithDropout(const Layer &inL, const WeightMatrix &weN, const Layer &ouL, Layer &outInL, const Layer &dropoutMask, int skipBiasIndex = -1);

    // ---- Обновление весов (обратный проход с gradient descent) ----

    // Обновляет веса с помощью обычного SGD: w -= lr * gradient
    // Градиент для каждого веса: weight[j][i] -= lr * error_out[j] * output_in[i]
    //
    // Параметры:
    //   inL          — входной слой (выходы предыдущего слоя)
    //   weN          — матрица весов (обновляется)
    //   ouL          — выходной слой (ошибки)
    //   learningRate — шаг обучения
    void backwardPass(const Layer &inL, WeightMatrix &weN, const Layer &ouL, float learningRate);

    // Обновляет веса с помощью Adam-оптимизатора.
    // Для каждого веса поддерживает скользящее среднее градиента (m) и
    // скользящее среднее квадрата градиента (v), с коррекцией смещения.
    //
    // Параметры:
    //   inL          — входной слой
    //   weN          — матрица весов (обновляется)
    //   ouL          — выходной слой (ошибки)
    //   learningRate — шаг обучения
    //   m            — первый момент (скорость), обновляется на месте
    //   v            — второй момент (накопление), обновляется на месте
    //   t            — текущий timestep (для bias correction)
    void backwardPassAdam(const Layer &inL, WeightMatrix &weN, const Layer &ouL, float learningRate, WeightMatrix &m, WeightMatrix &v, int t);

    // Обновляет веса с помощью Momentum-оптимизатора.
    // Накапливает экспоненциально убывающую сумму градиентов:
    //   velocity = momentum * velocity + gradient
    //   weight -= lr * velocity
    //
    // Параметры:
    //   inL          — входной слой
    //   weN          — матрица весов (обновляется)
    //   ouL          — выходной слой (ошибки)
    //   learningRate — шаг обучения
    //   velocity     — матрица скоростей (накапливается между вызовами)
    void backwardPassMomentum(const Layer &inL, WeightMatrix &weN, const Layer &ouL, float learningRate, WeightMatrix &velocity);

    // ---- Утилиты ----

    // Заполняет выходной слой целевыми значениями и вычисляет начальную ошибку.
    // Для каждого нейрона: output = target[i], error = output * (1 - output)
    // (последнее — производная MSE по активации для сигмоиды).
    //
    // Параметры:
    //   targets — массив целевых значений
    //   len     — длина массива
    //   ouL     — выходной слой (записываются output и error)
    static void setOutputError(const float targets[], int len, Layer &ouL);
};

// ============================================================================
// BatchNormParams — параметры Batch Normalization
// ============================================================================
//
// Batch Normalization нормализует выходы каждого нейрона (z) к нулевому
// среднему и единичной дисперсии внутри мини-батча, а затем применяет
// обучаемые параметры масштабирования (gamma) и сдвига (beta).
//
// Зачем это нужно:
//   • Ускоряет обучение (можно использовать больший learning rate);
//   • Уменьшает чувствительность к начальной инициализации;
//   • Действует как лёгкий регуляризатор.
//
// Во время инференса нормализация использует скользящие средние (runningMean,
// runningVariance), накопленные при обучении, потому что мини-батчей нет.
//
// Структура организована как WeightMatrix, потому что BatchNorm применяется
// к каждому весовому соединению в некоторых реализациях, хотя классический
// BatchNorm применяется к каждому нейрону. Здесь gamma/beta хранятся в той
// же форме, что и веса, для удобства индексации.
//
struct BatchNormParams {
    WeightMatrix gamma;             // Масштабирующий параметр (обучаемый); изначально 1.0
    WeightMatrix beta;              // Сдвигающий параметр (обучаемый); изначально 0.0
    WeightMatrix runningMean;       // Скользящее среднее (для инференса)
    WeightMatrix runningVariance;   // Скользящая дисперсия (для инференса)
    float momentum = 0.9f;          // Коэффициент затухания для скользящих средних
    float epsilon = 1e-5f;          // Маленькое число для предотвращения деления на ноль при нормализации
    bool isTraining = true;         // true = использовать статистику батча; false = использовать runningMean/runningVariance
};

// ============================================================================
// MiniBatchTrainer — утилиты для мини-батч обучения
// ============================================================================
//
// Мини-батч обучение обрабатывает несколько примеров перед обновлением весов.
// Это даёт:
//   • Более стабильный градиент (усреднение шума);
//   • Лучшее использование GPU/CPU (векторизация);
//   • Возможность использовать больший learning rate.
//
// Класс предоставляет статические методы для:
//   • инициализации аккумуляторов градиентов;
//   • накопления градиентов от каждого примера;
//   • применения усреднённого градиента к весам;
//   • сброса аккумуляторов для следующего батча.
//
class MiniBatchTrainer {
public:
    // GradientAccumulator — временное хранилище для суммы градиентов
    // внутри мини-батча.
    struct GradientAccumulator {
        std::vector<WeightMatrix> gradients;  // Сумма градиентов для каждой матрицы весов
        Layer outputErrorSum;                  // Сумма ошибок выходного слоя
        int sampleCount = 0;                   // Количество накопленных примеров
    };

    // Инициализирует аккумулятор нулями под заданную структуру весов.
    //
    // Параметры:
    //   acc     — аккумулятор (записываются нулевые градиенты)
    //   weights — эталонные веса (определяют форму матриц)
    //   outputSize — размер выходного слоя (для outputErrorSum)
    static void initGradient(GradientAccumulator &acc, const std::vector<WeightMatrix> &weights, int outputSize);

    // Добавляет градиенты одного примера в аккумулятор.
    //
    // Параметры:
    //   acc        — аккумулятор (обновляется)
    //   gradients  — градиенты текущего примера
    //   outputError — ошибка выходного слоя текущего примера
    static void accumulateGradient(GradientAccumulator &acc, const std::vector<WeightMatrix> &gradients, const Layer &outputError);

    // Применяет усреднённые градиенты к весам сети.
    // Делит сумму градиентов на batchSize и вызывает backwardPass.
    //
    // Параметры:
    //   net          — контроллер сети (для доступа к NeuralNet)
    //   acc          — аккумулятор с накопленными градиентами
    //   learningRate — шаг обучения
    //   batchSize    — размер батча (для усреднения)
    static void applyGradient(NeuralNetController &net, GradientAccumulator &acc, float learningRate, int batchSize);

    // Сбрасывает аккумулятор для следующего батча (обнуляет все градиенты).
    static void resetGradient(GradientAccumulator &acc);
};

// ============================================================================
// AdamState — состояние Adam-оптимизатора
// ============================================================================
//
// Adam (Adaptive Moment Estimation) поддерживает два скользящих средних для
// каждого веса:
//   m — первый момент (экспоненциально убывающее среднее градиентов);
//   v — второй момент (экспоненциально убывающее среднее квадратов градиентов).
//
// t — глобальный счётчик шагов, необходимый для коррекции смещения
// (bias correction), потому что в начале обучения m и v смещены к нулю.
//
// Каждый элемент вектора соответствует одной матрице весов сети.
//
struct AdamState {
    std::vector<WeightMatrix> m;  // Первый момент (скорость) для каждой весовой матрицы
    std::vector<WeightMatrix> v;  // Второй момент (накопление) для каждой весовой матрицы
    int t = 0;                     // Глобальный счётчик шагов (bias correction)
};

// ============================================================================
// MomentumState — состояние Momentum-оптимизатора
// ============================================================================
//
// Momentum-оптимизатор накапливает «скорость» (velocity) — экспоненциально
// убывающую сумму прошлых градиентов. Это позволяет:
//   • Разогнаться через плоские области функции потерь;
//   • Сгладить осцилляции в «оврагах»;
//   • Быстрее сходиться к минимуму.
//
// Формула обновления:
//   velocity = momentum * velocity + gradient
//   weight  -= learningRate * velocity
//
// Каждый элемент вектора соответствует одной матрице весов сети.
//
struct MomentumState {
    std::vector<WeightMatrix> velocity;  // Матрицы скоростей для каждой весовой матрицы
};
