#include "NeuralNet.h"

#include <algorithm>

// ============================================================================
// Конструктор NeuralNet
// ============================================================================
//
// Назначение:
//   Инициализирует генератор псевдослучайных чисел (RNG) случайным seed'ом
//   из std::random_device. Этот генератор используется во всех методах,
//   требующих случайности: инициализация весов, dropout-маски и т.д.
//
// Почему один RNG на объект, а не создавать новый каждый раз?
//   Создание std::uniform_real_distribution и посев RNG на каждом вызове
//   было бы катастрофически медленным (в 20+ раз). Один долгоживущий
//   генератор — стандартная практика в C++.
//
NeuralNet::NeuralNet()
    : rng_(std::random_device{}())
{
}

// ============================================================================
// random — генерация случайного числа
// ============================================================================
//
// Назначение:
//   Возвращает случайное float-число из равномерного распределения [low, high].
//
// Входные параметры:
//   low  — нижняя граница диапазона (включительно)
//   high — верхняя граница диапазона (включительно)
//
// Выходные данные:
//   float — случайное число в диапазоне [low, high]
//
// Почему не std::rand()?
//   std::rand() имеет плохое качество случайности, ограниченную точность
//   и зависит от платформы. std::uniform_real_distribution с
//   std::default_random_engine даёт предсказуемое, качественное распределение.
//
float NeuralNet::random(float low, float high)
{
    std::uniform_real_distribution<float> dist(low, high);
    return dist(rng_);
}

// ============================================================================
// sigmoid — сигмоидальная функция активации
// ============================================================================
//
// Формула:
//   sigmoid(x) = 1 / (1 + exp(-x))
//
// Диапазон выходных значений: (0, 1)
//
// Назначение:
//   Нелинейное преобразование, сжимающее любое входное число в интервал (0, 1).
//   Исторически первая функция активации в нейронных сетях. Интерпретируется
//   как «степень активации» нейрона: 0 = полностью неактивен, 1 = полностью активен.
//
// Входные параметры:
//   x — взвешенная сумма входов (z = sum(w_i * x_i) + bias)
//
// Выходные данные:
//   float — значение в диапазоне (0, 1)
//
// Зачем нужна защита от переполнения (clamp при |x| > 20)?
//   std::exp(-x) при больших положительных x даёт exp(-500) ~ 0 (безопасно),
//   но при больших отрицательных x даёт exp(500) = inf (переполнение!).
//   Это приводит к nan в формуле 1 / (1 + inf) = 0 — технически верно,
//   но промежуточные вычисления могут стать некорректными.
//   Порог +/-20 выбран потому, что:
//     sigmoid(20)  = 0.9999999979... (уже практически 1)
//     sigmoid(-20) = 0.0000000021... (уже практически 0)
//   То есть после 20 функция уже насыщена, и точное вычисление не нужно.
//
float NeuralNet::sigmoid(float x)
{
    // Защита от переполнения: при x > 20 сигмоида уже ~= 1.0
    if (x > 20.0f) return 1.0f;
    // При x < -20 сигмоида уже ~= 0.0
    if (x < -20.0f) return 0.0f;
    // Основная формула: 1 / (1 + e^(-x))
    return 1.0f / (1.0f + std::exp(-x));
}

// ============================================================================
// sigmoidDerivative — производная сигмоиды
// ============================================================================
//
// Формула:
//   sigmoid'(x) = sigmoid(x) * (1 - sigmoid(x)) = output * (1 - output)
//
// Назначение:
//   Вычисляет производную сигмоиды для обратного распространения ошибки.
//   Производная показывает, насколько сильно изменится выход при малом
//   изменении входа — это и есть «локальный градиент».
//
// Входные параметры:
//   activatedOutput — УЖЕ вычисленное значение sigmoid(x) (результат прямого прохода)
//
//   ВНИМАНИЕ: параметр называется activatedOutput, а не x, потому что
//   производная сигмоиды выражается через ЕЁ ЖЕ ВЫХОД, а не через вход.
//   Это позволяет избежать повторного вычисления exp() — значительная
//   оптимизация, так как exp() — дорогая операция.
//
// Выходные данные:
//   float — значение производной в диапазоне (0, 0.25]
//           (максимум 0.25 при output = 0.5, минимум ~0 при output ~= 0 или 1)
//
// Проблема затухания градиента:
//   При output -> 0 или output -> 1 производная -> 0. Это означает, что
//   когда нейрон «уверен» в своём ответе (очень близок к 0 или 1), градиент
//   практически исчезает, и обучение замедляется. Это главная проблема
//   сигмоиды, из-за которой для глубоких сетей предпочитают ReLU.
//
float NeuralNet::sigmoidDerivative(float activatedOutput)
{
    // Производная сигмоиды: d/dx sigmoid(x) = sigmoid(x) * (1 - sigmoid(x))
    // Поскольку activatedOutput = sigmoid(x), получаем: output * (1 - output)
    return activatedOutput * (1.0f - activatedOutput);
}

// ============================================================================
// relu — Rectified Linear Unit (выпрямленный линейный单元)
// ============================================================================
//
// Формула:
//   relu(x) = max(0, x) = { x,  если x > 0
//                           { 0,  если x <= 0
//
// Диапазон выходных значений: [0, +inf)
//
// Назначение:
//   Самая популярная функция активации для скрытых слоёв. Пропускает
//   положительные значения без изменений и обнуляет отрицательные.
//   Создаёт разреженную активацию (многие нейроны = 0), что полезно
//   для регуляризации и скорости.
//
// Входные параметры:
//   x — взвешенная сумма входов (z)
//
// Выходные данные:
//   float — x если x > 0, иначе 0
//
// Почему ReLU лучше сигмоиды для глубоких сетей?
//   1. Не насыщается при положительных x — градиент всегда = 1,
//      поэтому не возникает проблема затухания градиента.
//   2. Вычислительно дешевле: одно сравнение вместо exp() + деления.
//   3. Создаёт разреженность: ~50% нейронов обнулены, что действует
//      как лёгкая регуляризация.
//
// Проблема «мёртвых нейронов»:
//   Если нейрон попал в область x < 0 и градиент обнулился, он может
//   навсегда остаться «мёртвым» (никогда не активируется). Решение —
//   Leaky ReLU, которая пропускает маленький градиент и при x < 0.
//
float NeuralNet::relu(float x)
{
    // Если вход положительный — пропускаем, иначе обнуляем
    return x > 0.0f ? x : 0.0f;
}

// ============================================================================
// reluDerivative — производная ReLU
// ============================================================================
//
// Формула:
//   relu'(x) = { 1,  если x > 0
//              { 0,  если x <= 0
//
// Назначение:
//   Производная ReLU для обратного распространения. Показывает, что:
//   - При x > 0: градиент проходит без изменений (производная = 1)
//   - При x <= 0: градиент полностью блокируется (производная = 0)
//
// Входные параметры:
//   x — исходное значение z (pre-activation, ДО применения ReLU)
//
//   ВАЖНО: в отличие от sigmoidDerivative, здесь нужен именно x (pre-activation),
//   а не activatedOutput. Это потому, что производная ReLU зависит от знака x,
//   а не от значения output (output = 0 и для x = -1, и для x = -100, но
//   производная одинакова = 0).
//
// Выходные данные:
//   float — 1 если x > 0, иначе 0
//
float NeuralNet::reluDerivative(float x)
{
    // Градиент проходит только через положительные входы
    return x > 0.0f ? 1.0f : 0.0f;
}

// ============================================================================
// leakyRelu — «утекающая» версия ReLU
// ============================================================================
//
// Формула:
//   leakyRelu(x) = { x,       если x > 0
//                  { 0.01 * x, если x <= 0
//
// Диапазон выходных значений: (-inf, +inf)
//
// Назначение:
//   Решает проблему «мёртвых нейронов» обычного ReLU. Для отрицательных
//   значений вместо полного обнуления используется маленький наклон (0.01),
//   позволяющий градиенту «протекать» даже когда нейрон неактивен.
//
// Входные параметры:
//   x — взвешенная сумма входов (z)
//
// Выходные данные:
//   float — x если x > 0, иначе 0.01 * x
//
// Почему коэффициент именно 0.01?
//   Это эмпирическое значение из оригинальной статьи (Maas et al., 2013).
//   Слишком маленький коэффициент (0.001) — почти не помогает, слишком
//   большой (0.1) — делает функцию слишком линейной. 0.01 — золотая
//   середина, подтверждённая экспериментами на многих датасетах.
//
// Когда использовать Leaky ReLU вместо обычного ReLU?
//   - При проблемах с «мёртвыми нейронами» (большая часть сети не активируется);
//   - При обучении с большим learning rate (ReLU может «убить» нейроны);
//   - В глубоких сетях, где риск затухания градиента выше.
//
float NeuralNet::leakyRelu(float x)
{
    // Положительные — без изменений, отрицательные — с маленьким наклоном 0.01
    return x > 0.0f ? x : 0.01f * x;
}

// ============================================================================
// leakyReluDerivative — производная Leaky ReLU
// ============================================================================
//
// Формула:
//   leakyRelu'(x) = { 1,    если x > 0
//                   { 0.01, если x <= 0
//
// Назначение:
//   Производная Leaky ReLU. В отличие от ReLU, градиент НЕ обнуляется при
//   x < 0, а равен 0.01 — маленький, но ненулевой. Это гарантирует, что
//   нейрон всегда может «оживиться» при обновлении весов.
//
// Входные параметры:
//   x — исходное значение z (pre-activation)
//
// Выходные данные:
//   float — 1 если x > 0, иначе 0.01
//
float NeuralNet::leakyReluDerivative(float x)
{
    // Через положительные — полный градиент, через отрицательные — маленький (0.01)
    return x > 0.0f ? 1.0f : 0.01f;
}

// ============================================================================
// tanhActivation — гиперболический тангенс
// ============================================================================
//
// Формула:
//   tanh(x) = (exp(x) - exp(-x)) / (exp(x) + exp(-x))
//           = 2 * sigmoid(2x) - 1
//
// Диапазон выходных значений: (-1, 1)
//
// Назначение:
//   S-образная функция, похожая на сигмоиду, но центрированная вокруг нуля.
//   Выход в диапазоне (-1, 1) означает, что нейрон может быть как
//   «возбуждающим» (положительный выход), так и «тормозящим» (отрицательный).
//
// Входные параметры:
//   x — взвешенная сумма входов (z)
//
// Выходные данные:
//   float — значение в диапазоне (-1, 1)
//
// Почему tanh лучше сигмоиды?
//   1. Центрирован вокруг нуля: среднее значение выхода ~= 0, а не 0.5.
//      Это ускоряет обучение, потому что градиенты не смещены в одну сторону.
//   2. Более крутые производные: переход от -1 к 1 происходит резче,
//      что даёт более выраженные градиенты в области перехода.
//
// Недостатки (как и у сигмоиды):
//   - Насыщается при больших |x|, градиент -> 0
//   - Требует вычисления exp(), что дороже ReLU
//
float NeuralNet::tanhActivation(float x)
{
    // Используем стандартную функцию std::tanh из <cmath>
    return std::tanh(x);
}

// ============================================================================
// tanhDerivative — производная гиперболического тангенса
// ============================================================================
//
// Формула:
//   tanh'(x) = 1 - tanh^2(x) = 1 - output^2
//
// Назначение:
//   Производная tanh для обратного распространения. Как и у сигмоиды,
//   выражается через ВЫХОД функции, а не через вход — это позволяет
//   избежать повторного вычисления tanh/exp.
//
// Входные параметры:
//   activatedOutput — УЖЕ вычисленное значение tanh(x)
//
// Выходные данные:
//   float — значение производной в диапазоне (0, 1]
//           (максимум 1 при output = 0, минимум ~0 при output ~= +/-1)
//
// Сравнение с sigmoidDerivative:
//   sigmoidDerivative: максимум 0.25 (при output = 0.5)
//   tanhDerivative:    максимум 1.0  (при output = 0)
//   У tanh градиенты в 4 раза сильнее в центре — это одна из причин,
//   почему tanh обучается быстрее сигмоиды.
//
float NeuralNet::tanhDerivative(float activatedOutput)
{
    // Производная tanh: d/dx tanh(x) = 1 - tanh^2(x) = 1 - output^2
    return 1.0f - activatedOutput * activatedOutput;
}

// ============================================================================
// activate — универсальный диспетчер функций активации
// ============================================================================
//
// Назначение:
//   Выбирает и вызывает нужную функцию активации на основе ActivationType.
//   Это позволяет хранить тип активации на уровне сети (activationType),
//   а не хардкодить её в каждом вызове.
//
// Входные параметры:
//   x    — взвешенная сумма входов (z)
//   type — тип функции активации (SIGMOID, RELU, LEAKY_RELU, TANH)
//
// Выходные данные:
//   float — результат выбранной функции активации
//
// Почему switch, а не таблица указателей на функции?
//   Компилятор оптимизирует switch в jump table при последовательных
//   enum-значениях, так что производительность одинакова. Switch более
//   читаем и не требует отдельного объявления массива функций.
//
float NeuralNet::activate(float x, ActivationType type)
{
    switch (type)
    {
    case ACTIVATION_RELU:
        return relu(x);
    case ACTIVATION_LEAKY_RELU:
        return leakyRelu(x);
    case ACTIVATION_TANH:
        return tanhActivation(x);
    case ACTIVATION_SIGMOID:
    default:
        return sigmoid(x);
    }
}

// ============================================================================
// activateDerivative — универсальный диспетчер производных активации
// ============================================================================
//
// Назначение:
//   Выбирает и вызывает нужную производную функции активации на основе типа.
//   Используется при обратном распространении для вычисления локального градиента.
//
// Входные параметры:
//   activatedOutput — значение ПОСЛЕ активации (результат activate())
//                     Для ReLU/Leaky ReLU интерпретируется как pre-activation x
//                     (это историческая несогласованность API)
//   type            — тип функции активации
//
// Выходные данные:
//   float — значение производной выбранной функции
//
// Важное замечание о семантике параметра:
//   Для sigmoid и tanh: параметр = post-activation output (output = f(x))
//   Для relu и leakyRelu: параметр = pre-activation x (вход ДО активации)
//   Это несоответствие возникло исторически, но работает корректно, потому что:
//     - sigmoidDerivative использует output * (1 - output), и output уже вычислен
//     - reluDerivative проверяет знак x > 0, и output > 0 <=> x > 0 для ReLU
//     - tanhDerivative использует 1 - output^2, и output уже вычислен
//     - leakyReluDerivative проверяет знак x > 0, и output > 0 <=> x > 0 для Leaky ReLU
//
float NeuralNet::activateDerivative(float activatedOutput, ActivationType type)
{
    switch (type)
    {
    case ACTIVATION_RELU:
        return reluDerivative(activatedOutput);
    case ACTIVATION_LEAKY_RELU:
        return leakyReluDerivative(activatedOutput);
    case ACTIVATION_TANH:
        return tanhDerivative(activatedOutput);
    case ACTIVATION_SIGMOID:
    default:
        return sigmoidDerivative(activatedOutput);
    }
}

// ============================================================================
// forwardPass — прямой проход (feed-forward propagation)
// ============================================================================
//
// Назначение:
//   Вычисляет выходы нейронов текущего слоя на основе входов и весов.
//   Это основной механизм «прямого распространения» сигнала в нейронной сети.
//
// Математика:
//   Для каждого нейрона j выходного слоя:
//     z_j = sum_i(input[i] * weight[j][i])        — взвешенная сумма
//     output[j] = activate(z_j)                    — применение активации
//
//   В матричной форме: z = W * x, output = activate(z)
//
//   Где:
//     W — матрица весов (weN), размер [fanOut][fanIn]
//     x — вектор входов (inL), размер [fanIn]
//     z — вектор взвешенных сумм, размер [fanOut]
//
// Входные параметры:
//   inL             — входной слой: Neuron.output содержит активации предыдущего слоя
//   weN             — матрица весов: weN[j][i] — вес от i-го входа к j-му выходу
//   ouL             — выходной слой (результат): сюда записываются z и output
//   skipBiasIndex   — индекс нейрона, для которого ПРОПУСКАЕТСЯ вычисление.
//                     Обычно = -1 (никого не пропускать).
//                     Используется при BatchNorm, где bias-нейрон обрабатывается
//                     отдельно через параметры gamma/beta.
//
// Выходные данные:
//   ouL[j].z      — взвешенная сумма для j-го нейрона (pre-activation)
//   ouL[j].output — результат активации (post-activation)
//
// Архитектурное решение:
//   Почему z и output записываются в ouL, а не возвращаются как vector<float>?
//   Потому что обратное распространение требует ОБЕИХ величин:
//     - z нужен для вычисления производной активации (ReLU, Leaky ReLU)
//     - output нужен для вычисления градиента и передачи следующему слою
//   Хранение их в Neuron — единый источник истины для обоих проходов.
//
// Почему нет отдельного bias-вектора?
//   Bias встроен как первый элемент входного вектора (inL[0]) с фиксированным
//   значением 1.0. Это эквивалентно добавлению столбца единиц в матрицу X,
//   что превращает affine преобразование (Wx + b) в линейное (W'x').
//   Преимущество: один цикл вместо двух (не нужно отдельно прибавлять bias).
//
void NeuralNet::forwardPass(const Layer &inL, const WeightMatrix &weN, Layer &ouL, int skipBiasIndex)
{
    // fanOut — количество нейронов в выходном слое (количество строк в матрице весов)
    const int fanOut = static_cast<int>(weN.size());
    // fanIn — количество входов (количество столбцов, включая bias)
    const int fanIn  = static_cast<int>(weN[0].size());

    // Для каждого нейрона выходного слоя...
    for (int i = 0; i < fanOut; i++)
    {
        // Пропускаем нейрон с указанным индексом (обычно bias-нейрон при BatchNorm)
        if (i == skipBiasIndex) continue;

        // Вычисляем взвешенную сумму: z = sum(input[u] * weight[i][u])
        float sum = 0.0f;
        for (int u = 0; u < fanIn; u++)
            sum += inL[u].output * weN[i][u];

        // Сохраняем pre-activation значение (нужно для производных при обратном проходе)
        ouL[i].z = sum;
        // Применяем функцию активации и записываем post-activation результат
        ouL[i].output = activate(sum, activationType);
    }
}

// ============================================================================
// forwardPassWithDropout — прямой проход с Dropout-регуляризацией
// ============================================================================
//
// Назначение:
//   То же, что forwardPass, но случайно «выключает» часть нейронов согласно
//   dropoutRate. Это предотвращает переобучение (co-adaptation), заставляя
//   каждый нейрон учиться быть полезным независимо от других.
//
// Алгоритм Inverted Dropout (используется здесь):
//   1. Для каждого нейрона генерируем случайное число r ~ Uniform(0, 1)
//   2. Если r > dropoutRate: нейрон АКТИВЕН, output *= 1/(1-rate) (масштабирование)
//   3. Если r <= dropoutRate: нейрон ВЫКЛЮЧЕН, output = 0
//
// Зачем масштабирование 1/(1-rate)?
//   При обучении мы «выключаем» rate * 100% нейронов. Чтобы при инференсе
//   (когда dropout выключен) среднее значение выхода совпадало, нужно
//   компенсировать уменьшение на этапе обучения.
//
//   Пример: dropoutRate = 0.5, output = 10
//     - При обучении: ~50% нейронов выключены, оставшиеся умножаются на 1/(1-0.5) = 2
//       Средний выход: 0.5 * 0 + 0.5 * (10 * 2) = 10
//     - При инференсе: все нейроны активны, выход = 10 (без изменений)
//     Средние значения совпадают — сеть ведёт себя одинаково!
//
// Входные параметры:
//   inL             — входной слой
//   weN             — матрица весов
//   ouL             — выходной слой (результат)
//   dropoutMask     — маска dropout: output = 1/(1-rate) если активен, 0 если выключен
//   dropoutRate     — вероятность выключения нейрона (0.0 = без dropout, 0.5 = 50%)
//   skipBiasIndex   — индекс нейрона для пропуска (bias не дропаутится!)
//
// Выходные данные:
//   ouL[j].output — результат активации, умноженный на dropout-маску
//   dropoutMask[j].output — коэффициент масштабирования для j-го нейрона
//
// Почему dropout не применяется к bias?
//   Bias — это свободный параметр, не зависящий от входов. Его «выключение»
//   не имеет смысла: bias не может «переобучиться» в том же смысле, что веса.
//
void NeuralNet::forwardPassWithDropout(const Layer &inL, const WeightMatrix &weN, Layer &ouL, Layer &dropoutMask, float rate, int skipBiasIndex)
{
    const int fanOut = static_cast<int>(weN.size());
    const int fanIn  = static_cast<int>(weN[0].size());
    std::uniform_real_distribution<float> dist(0.0f, 1.0f);

    for (int i = 0; i < fanOut; i++)
    {
        if (i == skipBiasIndex) continue;

        // Взвешенная сумма (как в обычном forwardPass)
        float sum = 0.0f;
        for (int u = 0; u < fanIn; u++)
            sum += inL[u].output * weN[i][u];

        ouL[i].z = sum;
        ouL[i].output = activate(sum, activationType);

        // Генерируем dropout-маску:
        // С вероятностью (1 - rate) нейрон остаётся активным, но масштабируется
        // С вероятностью (rate) нейрон выключается (output = 0)
        dropoutMask[i].output = (dist(rng_) > rate) ? 1.0f / (1.0f - rate) : 0.0f;
        ouL[i].output *= dropoutMask[i].output;
    }
}

// ============================================================================
// reversePass — обратный проход для распространения ошибки
// ============================================================================
//
// Назначение:
//   «Распределяет» ошибку от выходного слоя обратно ко входному слою.
//   Это НЕ обновление весов — это вычисление градиента для предыдущего слоя.
//
// Математика (chain rule):
//   dL/d(input[i]) = sum_j(dL/d(output[j]) * d(output[j])/d(input[i]))
//                  = sum_j(error_out[j] * weight[j][i])
//
//   Где:
//     error_out[j] = dL/d(output[j]) — уже вычисленная ошибка j-го выходного нейрона
//     weight[j][i] — вес связи от i-го входа к j-му выходу
//
//   Интуитивно: вклад i-го входа в общую ошибку пропорционален сумме ошибок
//   всех нейронов, к которым он подключён, взвешенных по силе связи.
//
// Входные параметры:
//   inL             — слой, К КОТОРОМУ нужно propagate error (результат записывается сюда)
//   weN             — матрица весов [выход][вход]
//   ouL             — слой, ОТ КОТОРОГО propagate error (ouL[u].error уже вычислен)
//   skipBiasIndex   — индекс нейрона для пропуска (bias не получает градиент от предыдущего слоя)
//
// Выходные данные:
//   ouL[i].z      — взвешенная сумма ошибок (pre-activation «ошибка»)
//   ouL[i].output — активированная ошибка (после применения activate())
//   ouL[i].error  — НЕТ! Эта функция НЕ записывает error. Она записывает
//                   z и output, а error вычисляется отдельно в computeError.
//
// Почему результат записывается в ouL, а не в inL?
//   Это историческое название: «reverse pass» означает «идём назад по сети»,
//   но функция вычисляет значения для ouL (который станет inL для следующего
//   шага обратного прохода). То есть:
//     ouL здесь = слой, К КОТОРОМУ мы propagate error
//     inL здесь = слой, ОТ КОТОРОГО мы propagate error (через его веса)
//
void NeuralNet::reversePass(const Layer &inL, const WeightMatrix &weN, Layer &ouL, int skipBiasIndex)
{
    const int fanOut = static_cast<int>(weN.size());
    const int fanIn  = static_cast<int>(weN[0].size());

    // Для каждого нейрона входного слоя (к которому propagate error)...
    for (int i = 0; i < fanIn; i++)
    {
        if (i == skipBiasIndex) continue;

        // Суммируем ошибки всех выходных нейронов, взвешенные по весам
        // error_in[i] = sum_j(error_out[j] * weight[j][i])
        float sum = 0.0f;
        for (int u = 0; u < fanOut; u++)
            sum += inL[u].output * weN[u][i];

        ouL[i].z = sum;
        ouL[i].output = activate(sum, activationType);
    }
}

// ============================================================================
// randomizeWeights — инициализация весов случайными значениями
// ============================================================================
//
// Назначение:
//   Заполняет матрицу весов случайными значениями согласно выбранной стратегии.
//   Правильная инициализация критически важна для скорости сходимости.
//
// Стратегии инициализации:
//
//   INIT_UNIFORM:
//     w ~ Uniform(-weightRange, +weightRange), где weightRange = 0.5 по умолчанию
//     Простейший метод. Подходит для маленьких сетей, но не масштабируется
//     с размером слоя. Может привести к затуханию/взрыву градиентов.
//
//   INIT_XAVIER (Glorot, 2010):
//     w ~ Uniform(-scale, +scale), где scale = sqrt(2 / (fanIn + fanOut))
//     Сохраняет дисперсию активаций и градиентов при прямом и обратном проходе.
//     Оптимально для сигмоиды и tanh, потому что они симметричны относительно
//     масштаба входов. НЕ подходит для ReLU (не симметрична).
//
//   INIT_HE (Kaiming, 2015):
//     w ~ Uniform(-scale, +scale), где scale = sqrt(2 / fanIn)
//     Специально разработан для ReLU. Поскольку ReLU обнуляет ~50% входов,
//     дисперсия «эффективных» входов вдвое меньше. HE это компенсирует,
//     масштабируя только по fanIn (не fanOut).
//     Также хорошо работает с Leaky ReLU.
//
// Входные параметры:
//   we   — матрица весов для инициализации (изменяется на месте)
//   init — стратегия инициализации (INIT_UNIFORM, INIT_XAVIER, INIT_HE)
//
// Выходные данные:
//   we — заполнена случайными весами
//
// Почему используется равномерное распределение, а не нормальное?
//   Xavier и He в оригинальных статьях описывают оба варианта (uniform и normal).
//   Равномерное проще в реализации и даёт сопоставимые результаты.
//   Диапазон подобран так, чтобы дисперсия совпадала с формулой из статьи.
//
void NeuralNet::randomizeWeights(WeightMatrix &we, WeightInit init)
{
    // Масштаб по умолчанию для равномерной инициализации
    float scale = 0.5f;

    // Вычисляем масштаб на основе стратегии инициализации
    if (init == INIT_XAVIER || init == INIT_HE)
    {
        int fanIn = static_cast<int>(we[0].size());   // Количество входов
        int fanOut = static_cast<int>(we.size());      // Количество выходов

        if (init == INIT_XAVIER)
            // Xavier/Glorot: scale = sqrt(2 / (fanIn + fanOut))
            // Сохраняет дисперсию при прямом И обратном проходе
            scale = std::sqrt(2.0f / (fanIn + fanOut));
        else
            // He/Kaiming: scale = sqrt(2 / fanIn)
            // Компенсирует обнуление ReLU, сохраняя дисперсию при прямом проходе
            scale = std::sqrt(2.0f / fanIn);
    }

    // Заполняем матрицу весов случайными значениями из [-scale, +scale]
    std::uniform_real_distribution<float> dist(-scale, scale);
    for (auto &row : we)
        for (auto &w : row)
            w = dist(rng_);
}

// ============================================================================
// computeError — вычисление ошибки для нейронов предыдущего слоя
// ============================================================================
//
// Назначение:
//   Распределяет ошибку от выходного слоя обратно ко входам через веса.
//   Это ключевой шаг обратного распространения (backpropagation): после того
//   как мы вычислили ошибку выходного слоя, нужно понять, какие нейроны
//   предыдущего слоя «виноваты» в этой ошибке.
//
// Математика (chain rule):
//   dL/d(input[i]) = sum_j(dL/d(output[j]) * d(output[j])/d(input[i]))
//                  = sum_j(error_out[j] * weight[j][i])
//
//   Где:
//     dL/d(output[j]) = error_out[j] — ошибка j-го выходного нейрона
//     d(output[j])/d(input[i]) = weight[j][i] — вес связи
//
//   Интуитивно: если i-й вход сильно связан (большой вес) с нейроном,
//   у которого большая ошибка, то этот вход тоже «виноват».
//
// Входные параметры:
//   inL   — входной слой (информация о размерах, fanIn = weN[0].size())
//   weN   — матрица весов [выход][вход]
//   ouL   — выходной слой (ouL[u].error уже содержит вычисленную ошибку)
//   outInL — слой, КУДА записывается ошибка (outInL[i].error = ...)
//
// Выходные данные:
//   outInL[i].error — вычисленная ошибка для i-го нейрона входного слоя
//
// Почему цикл до fanIn - 1?
//   Последний элемент входного слоя (индекс fanIn - 1) — это bias-нейрон
//   с фиксированным значением 1.0. У него нет «предыдущего слоя», к которому
//   можно propagate error, поэтому его ошибка не вычисляется.
//
void NeuralNet::computeError(const Layer &inL, const WeightMatrix &weN, const Layer &ouL, Layer &outInL)
{
    const int fanIn  = static_cast<int>(weN[0].size());
    const int fanOut = static_cast<int>(weN.size());

    // Для каждого входа (кроме bias, индекс fanIn - 1)...
    for (int i = 0; i < fanIn - 1; i++)
    {
        // Суммируем ошибки всех выходных нейронов, взвешенные по весам
        float err = 0.0f;
        for (int u = 0; u < fanOut; u++)
            err += weN[u][i] * ouL[u].error;

        outInL[i].error = err;
    }
}

// ============================================================================
// computeErrorWithDropout — вычисление ошибки с учётом Dropout-маски
// ============================================================================
//
// Назначение:
//   То же, что computeError, но учитывает dropout-маску. Если нейрон был
//   «выключен» при прямом проходе, его ошибка НЕ должна распространяться
//   обратно — он не участвовал в вычислении.
//
// Математика:
//   dL/d(input[i]) = sum_j(error_out[j] * weight[j][i] * mask[j])
//
//   Где mask[j] = 0 если нейрон был выключен, 1/(1-rate) если активен.
//   Умножение на маску гарантирует, что «мёртвые» нейроны не получают градиент.
//
// Входные параметры:
//   inL           — входной слой
//   weN           — матрица весов
//   ouL           — выходной слой (ouL[u].error уже вычислен)
//   outInL        — слой для записи ошибки
//   dropoutMask   — маска dropout: output = 0 если выключен, 1/(1-rate) если активен
//   skipBiasIndex — индекс для пропуска
//
// Выходные данные:
//   outInL[i].error — ошибка с учётом dropout
//
void NeuralNet::computeErrorWithDropout(const Layer &inL, const WeightMatrix &weN, const Layer &ouL, Layer &outInL, const Layer &dropoutMask, int skipBiasIndex)
{
    const int fanIn  = static_cast<int>(weN[0].size());
    const int fanOut = static_cast<int>(weN.size());

    for (int i = 0; i < fanIn - 1; i++)
    {
        float err = 0.0f;
        for (int u = 0; u < fanOut; u++)
            // Ошибка умножается на dropout-маску: если нейрон был выключен (mask = 0),
            // его вклад в ошибку предыдущего слоя = 0
            err += weN[u][i] * ouL[u].error * dropoutMask[u].output;

        outInL[i].error = err;
    }
}

// ============================================================================
// backwardPass — обновление весов через SGD (стохастический градиентный спуск)
// ============================================================================
//
// Назначение:
//   Обновляет матрицу весов на основе вычисленных ошибок и градиентов.
//   Это финальный шаг обучения: после того как error вычислен для каждого
//   нейрона, нужно изменить веса так, чтобы ошибка уменьшилась.
//
// Математика:
//   dL/d(weight[j][i]) = dL/d(output[j]) * d(output[j])/d(z_j) * d(z_j)/d(weight[j][i])
//                      = error[j] * activate'(output[j]) * input[i]
//
//   Обновление веса (SGD):
//     weight[j][i] += learningRate * error[j] * activate'(output[j]) * input[i]
//
//   Знак «+» потому что error[j] уже определён как (target - output),
//   то есть это уже антиградиент (направление уменьшения ошибки).
//
//   Полная формула:
//     delta[j][i] = learningRate * error[j] * activate'(z_j) * input[i]
//     weight[j][i] += delta[j][i]
//
//   Где:
//     error[j] — ошибка j-го выходного нейрона (dL/d(output[j]))
//     activate'(output[j]) — производная активации (d(output[j])/d(z_j))
//     input[i] — выход i-го нейрона предыдущего слоя (d(z_j)/d(weight[j][i]))
//     learningRate — шаг обучения (learning rate)
//
// Gradient clipping (обрезание градиента):
//   Перед обновлением весов градиент обрезается до [-5.0, +5.0].
//   Это предотвращает «взрыв градиентов» — ситуацию, когда градиент
//   становится слишком большим и веса «улетают» в бесконечность,
//   что приводит к NaN в вычислениях.
//
//   Почему именно +/-5.0?
//   Это эмпирическое значение. Слишком маленькое значение (0.1) будет
//   слишком агрессивно обрезать полезные градиенты. Слишком большое (100)
//   не защитит от NaN. 5.0 — компромисс: достаточно большой, чтобы не
//   мешать обучению, но достаточно маленький, чтобы предотвратить NaN.
//
// Входные параметры:
//   inL          — входной слой: inL[u].output — выход i-го нейрона предыдущего слоя
//   weN          — матрица весов (обновляется на месте)
//   ouL          — выходной слой: ouL[i].error — ошибка, ouL[i].output — активация
//   learningRate — шаг обучения (learning rate, обычно 0.01 - 1.0)
//
// Выходные данные:
//   weN — обновлённая матрица весов
//
void NeuralNet::backwardPass(const Layer &inL, WeightMatrix &weN, const Layer &ouL, float learningRate)
{
    const int fanOut = static_cast<int>(weN.size());
    const int fanIn  = static_cast<int>(weN[0].size());

    // Для каждого нейрона выходного слоя...
    for (int i = 0; i < fanOut; i++)
    {
        // Вычисляем производную активации по выходу нейрона
        float deriv = activateDerivative(ouL[i].output, activationType);
        // Локальный градиент = ошибка * производная активации
        // Это dL/d(z_j) — производная функции потерь по взвешенной сумме
        float grad = ouL[i].error * deriv;

        // Gradient clipping: обрезание градиента для предотвращения взрыва
        // Если градиент слишком большой, ограничиваем его до +/-5.0
        // Это защищает от NaN и нестабильного обучения
        if (grad > 5.0f) grad = 5.0f;
        if (grad < -5.0f) grad = -5.0f;

        // Обновляем каждый вес, ведущий к этому нейрону
        // delta = learningRate * grad * input[u]
        // weight += delta (знак «+» потому что grad = target - output)
        for (int u = 0; u < fanIn; u++)
            weN[i][u] += learningRate * grad * inL[u].output;
    }
}

// ============================================================================
// backwardPassAdam — обновление весов через Adam-оптимизатор
// ============================================================================
//
// Назначение:
//   Обновляет веса с помощью Adam (Adaptive Moment Estimation) — одного из
//   самых популярных оптимизаторов. Adam сочетает преимущества двух методов:
//     - Momentum (скользящее среднее градиентов) — для ускорения
//     - RMSProp (скользящее среднее квадратов градиентов) — для адаптивного LR
//
// Математика Adam:
//
//   1. Вычисление градиента (как в SGD):
//        g = error[j] * activate'(output[j]) * input[u]
//
//   2. Обновление первого момента (экспоненциально убывающее среднее градиента):
//        m[t] = beta1 * m[t-1] + (1 - beta1) * g
//
//   3. Обновление второго момента (экспоненциально убывающее среднее квадрата):
//        v[t] = beta2 * v[t-1] + (1 - beta2) * g^2
//
//   4. Коррекция смещения (bias correction):
//        m_hat = m[t] / (1 - beta1^t)
//        v_hat = v[t] / (1 - beta2^t)
//
//      Зачем коррекция? В начале обучения m и v смещены к нулю (инициализация = 0).
//      Коррекция компенсирует это смещение, делая оценку несмещённой.
//
//   5. Обновление веса:
//        weight += learningRate * sqrt(1 - beta2^t) / (1 - beta1^t) * m_hat / (sqrt(v_hat) + epsilon)
//
//      Упрощённо: weight += lr_hat * m_hat / (sqrt(v_hat) + epsilon)
//
//      Где lr_hat = learningRate * sqrt(1 - beta2^t) / (1 - beta1^t) —
//      это learning rate с учётом коррекции смещения.
//
//   Параметры по умолчанию:
//     beta1  = 0.9    — затухание первого момента (быстрое среднее)
//     beta2  = 0.999  — затухание второго момента (медленное среднее)
//     epsilon = 1e-8  — защита от деления на ноль
//
//   Почему Adam лучше SGD?
//     - Адаптивный learning rate: каждый вес обновляется со своей скоростью
//     - Меньше осцилляций: второй момент «гасит» слишком большие градиенты
//     - Быстрее сходится: momentum разгоняет обучение в стабильных направлениях
//
// Входные параметры:
//   inL          — входной слой
//   weN          — матрица весов (обновляется)
//   ouL          — выходной слой (ошибки)
//   learningRate — шаг обучения
//   m            — первый момент (накапливается между вызовами)
//   v            — второй момент (накапливается между вызовами)
//   t            — текущий timestep (номер шага обучения)
//
// Выходные данные:
//   weN — обновлённые веса
//   m   — обновлённый первый момент
//   v   — обновлённый второй момент
//
void NeuralNet::backwardPassAdam(const Layer &inL, WeightMatrix &weN, const Layer &ouL, float learningRate, WeightMatrix &m, WeightMatrix &v, int t)
{
    const int fanOut = static_cast<int>(weN.size());
    const int fanIn  = static_cast<int>(weN[0].size());

    // Вычисляем beta1^t и beta2^t для коррекции смещения
    // Это можно было бы сделать через std::pow(adamBeta1, t), но
    // цикл быстрее для целых t (std::pow — дорогая функция с плавающей точкой)
    float beta1t = adamBeta1;
    float beta2t = adamBeta2;
    for (int k = 0; k < t; k++) {
        beta1t *= adamBeta1;
        beta2t *= adamBeta2;
    }

    // Скорректированный learning rate: lr_hat = lr * sqrt(1 - beta2^t) / (1 - beta1^t)
    float lrHat = learningRate * std::sqrt(1.0f - beta2t) / (1.0f - beta1t);

    // Для каждого нейрона выходного слоя...
    for (int i = 0; i < fanOut; i++)
    {
        float deriv = activateDerivative(ouL[i].output, activationType);
        float grad = ouL[i].error * deriv;

        // Gradient clipping — защита от NaN и взрыва градиентов
        if (grad > 5.0f) grad = 5.0f;
        if (grad < -5.0f) grad = -5.0f;

        // Для каждого веса...
        for (int u = 0; u < fanIn; u++)
        {
            // «Сырой» градиент для этого веса
            float g = grad * inL[u].output;

            // Обновляем первый момент (скользящее среднее градиента)
            m[i][u] = adamBeta1 * m[i][u] + (1.0f - adamBeta1) * g;

            // Обновляем второй момент (скользящее среднее квадрата градиента)
            v[i][u] = adamBeta2 * v[i][u] + (1.0f - adamBeta2) * g * g;

            // Коррекция смещения (компенсация нулевой инициализации m и v)
            float mHat = m[i][u] / (1.0f - beta1t);
            float vHat = v[i][u] / (1.0f - beta2t);

            // Обновление веса: weight += lr_hat * m_hat / (sqrt(v_hat) + epsilon)
            // Адаптивный learning rate: большие градиенты -> большие v -> меньший шаг
            weN[i][u] += lrHat * mHat / (std::sqrt(vHat) + adamEpsilon);
        }
    }
}

// ============================================================================
// backwardPassMomentum — обновление весов через Momentum-оптимизатор
// ============================================================================
//
// Назначение:
//   Обновляет веса с помощью SGD с импульсом (Momentum). Идея: накапливать
//   «скорость» (velocity) — экспоненциально убывающую сумму прошлых градиентов.
//   Если градиент стабильно указывает в одном направлении, скорость растёт
//   и обучение ускоряется. Если градиент «скачет», скорость сглаживает колебания.
//
// Математика:
//
//   1. Вычисление градиента:
//        g = error[j] * activate'(output[j]) * input[u]
//
//   2. Обновление скорости (velocity):
//        velocity[t] = momentum * velocity[t-1] + learningRate * g
//
//   3. Обновление веса:
//        weight[t] = weight[t-1] + velocity[t]
//
//   Где momentum — коэффициент «памяти» (обычно 0.9):
//     - momentum = 0: обычный SGD (без памяти)
//     - momentum = 0.9: скорость «помнит» последние ~10 шагов
//       (0.9^10 ~= 0.35, значит вклад градиента 10 шагов назад ещё 35%)
//     - momentum = 0.99: скорость «помнит» последние ~50 шагов
//
//   Почему Momentum лучше SGD?
//     - Разгон через плоские области: если градиент маленький но стабильный,
//       velocity нарастает и обучение ускоряется.
//     - Сглаживание осцилляций: в «оврагах» ландшафта градиент скачет
//       между стенками, но velocity усредняет эти колебания.
//     - Может «перепрыгнуть» через мелкие локальные минимумы.
//
//   Сравнение с Adam:
//     - Momentum проще (только один аккумулятор velocity, не два)
//     - Adam адаптивный (learning rate настраивается автоматически)
//     - Momentum требует ручной настройки learning rate
//     - Adam обычно сходится быстрее, но Momentum стабильнее
//
// Входные параметры:
//   inL          — входной слой
//   weN          — матрица весов (обновляется)
//   ouL          — выходной слой (ошибки)
//   learningRate — шаг обучения
//   velocity     — матрица скоростей (накапливается между вызовами)
//
// Выходные данные:
//   weN      — обновлённые веса
//   velocity — обновлённые скорости
//
void NeuralNet::backwardPassMomentum(const Layer &inL, WeightMatrix &weN, const Layer &ouL, float learningRate, WeightMatrix &velocity)
{
    const int fanOut = static_cast<int>(weN.size());
    const int fanIn  = static_cast<int>(weN[0].size());

    // Для каждого нейрона выходного слоя...
    for (int i = 0; i < fanOut; i++)
    {
        float deriv = activateDerivative(ouL[i].output, activationType);
        float grad = ouL[i].error * deriv;

        // Gradient clipping — защита от взрыва градиентов
        if (grad > 5.0f) grad = 5.0f;
        if (grad < -5.0f) grad = -5.0f;

        // Для каждого веса...
        for (int u = 0; u < fanIn; u++)
        {
            // Градиент, умноженный на learning rate
            float g = learningRate * grad * inL[u].output;

            // Обновляем скорость: velocity = momentum * old_velocity + gradient
            // Чем больше momentum, тем больше «память» о прошлых градиентах
            velocity[i][u] = momentum * velocity[i][u] + g;

            // Обновляем вес: weight += velocity
            // (velocity уже содержит learning rate, поэтому отдельного lr нет)
            weN[i][u] += velocity[i][u];
        }
    }
}

// ============================================================================
// setOutputError — установка целевых значений и вычисление ошибки выхода
// ============================================================================
//
// Назначение:
//   Заполняет выходной слой целевыми значениями (targets) и вычисляет
//   начальную ошибку для обратного распространения. Это «точка входа»
//   для backprop: ошибка начинается отсюда и распространяется назад.
//
// Математика (для MSE loss с сигмоидой):
//   Для выходного нейрона с сигмоидой:
//     error = (target - output) * activate'(z)
//
//   Однако в данной реализации используется упрощённая формула:
//     error = (target - output) * output * (1 - output)
//
//   Это комбинация:
//     - d(MSE)/d(output) = -(target - output) = output - target
//     - d(output)/d(z) = output * (1 - output) (производная сигмоиды)
//
//   Итого: d(MSE)/d(z) = (output - target) * output * (1 - output)
//
//   Но в коде записано как:
//     ouL[i].error = targets[i] - ouL[i].output
//   Это «сырая» ошибка (без производной активации). Производная активации
//   будет умножена позже в backwardPass через activateDerivative().
//
//   Почему так? Потому что backwardPass делает:
//     grad = error * activateDerivative(output)
//   То есть производная активации применяется в backwardPass, а не здесь.
//
// Входные параметры:
//   targets — массив целевых значений (desired outputs)
//   len     — длина массива targets (должна совпадать с размером ouL)
//   ouL     — выходной слой (записывается ошибка)
//
// Выходные данные:
//   ouL[i].error — ошибка i-го выходного нейрона (target - output)
//
void NeuralNet::setOutputError(const float targets[], int len, Layer &ouL)
{
    // Для каждого выходного нейрона: ошибка = целевое значение - фактический выход
    // Это d(MSE)/d(output) — производная MSE по выходу нейрона
    // Знак: target - output (а не output - target), потому что мы хотим
    // двигаться в направлении УМЕНЬШЕНИЯ ошибки (антиградиент)
    for (int i = 0; i < len; i++)
        ouL[i].error = targets[i] - ouL[i].output;
}
