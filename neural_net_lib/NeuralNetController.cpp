// --- Квадрат числа ---
//
// Назначение:
//   Вспомогательная функция для вычисления квадрата ошибки (MSE).
//   Используется в getError() для расчёта общей ошибки сети.
//
// Почему static:
//   Функция не зависит от состояния объекта — это чистая математика.
//   Объявление static предотвращает случайный доступ к this и
//   позволяет вызывать функцию без экземпляра класса.
//
// Параметры:
//   n — число для возведения в квадрат
// Возвращаемое значение:
//   n * n
float NeuralNetController::square(float n)
{
    return n * n;
}

// --- Инверсия весов ---
//
// Назначение:
//   Умножает все веса сети на -1. Не имеет практического смысла в обучении —
//   используется исключительно для тестирования и отладки.
//
// Почему так реализован:
//   Проходит по всем матрицам весов в обратном порядке (от выходного к
//   входному) и вызывает net_.reversePass() для каждой пары слоёв.
//   Параметр skipBias указывает индекс bias-нейрона в целевом слое,
//   чтобы не инвертировать веса, ведущие к bias (они не влияют на градиент).
//
//   Обратный порядок (от layerCount()-2 до 0) обусловлен тем, что
//   weights_.size() == layerCount() - 1, и weights_[i] соединяет
//   layers_[i] с layers_[i+1].
void NeuralNetController::reverseWeights()
{
    for (int i = layerCount() - 2; i >= 0; i--)
    {
        int skipBias = biasIndices_.at(i + 1);
        net_.reversePass(layers_.at(i + 1), weights_.at(i), layers_.at(i), skipBias);
    }
}

// --- Обучение: классификация (целевой класс) ---
//
// Назначение:
//   Выполняет полный цикл обучения на одном примере для задачи классификации.
//   Сеть должна «научиться» выдавать 1.0 на нейроне targetClass и 0.0 на
//   всех остальных нейронах выходного слоя.
//
// Алгоритм (4 шага):
//   1. forwardPass()  — вычисляет активации всех слоёв (предсказание);
//   2. setOutputError(targetClass) — вычисляет ошибку выходного слоя:
//      error[i] = (i == targetClass ? 1.0 : 0.0) - output[i];
//   3. computeErrors() — propagates ошибку назад через все скрытые слои
//      по правилу цепного правила (chain rule);
//   4. backwardPass() — обновляет веса на основе вычисленных градиентов.
//
// Почему так реализован:
//   Разделение на 4 отдельных метода позволяет переиспользовать их в
//   других вариантах обучения (train(const float[]), trainMiniBatch и т.д.).
//   Например, computeErrors() нужен и для классификации, и для регрессии.
//
// Параметры:
//   targetClass — номер целевого класса (индекс нейрона в выходном слое).
//   Например, targetClass = 3 означает, что 4-й нейрон должен выдать 1.0.
//
// Предусловия:
//   Входные данные должны быть установлены через setData() ДО вызова.
void NeuralNetController::train(int targetClass)
{
    forwardPass();
    setOutputError(targetClass);
    computeErrors();
    backwardPass();
}

// --- Обучение: регрессия (массив целевых значений) ---
//
// Назначение:
//   Аналог train(int), но для задач регрессии. Вместо дискретного класса
//   принимает массив непрерывных целевых значений для каждого нейрона
//   выходного слоя.
//
// Чем отличается от train(int):
//   train(int) использует one-hot encoding (один нейрон = 1.0, остальные = 0.0),
//   что подходит для классификации. train(const float[]) принимает
//   произвольные целевые значения, что нужно для регрессии (предсказание
//   цены, температуры, координат и т.д.).
//
// Алгоритм:
//   Тот же 4-шаговый процесс, но setOutputError(targets) вычисляет:
//   error[i] = targets[i] - output[i]  (без one-hot encoding).
//
// Параметры:
//   targets — массив целевых значений. Длина должна равняться количеству
//   нейронов в выходном слое.
//
// Предусловия:
//   Входные данные должны быть установлены через setData() ДО вызова.
void NeuralNetController::train(const float targets[])
{
    forwardPass();
    setOutputError(targets);
    computeErrors();
    backwardPass();
}

// --- Полная инициализация сети ---
//
// Назначение:
//   Подготавливает сеть к обучению: устанавливает bias-нейроны, создаёт
//   матрицы весов (если ещё не созданы), рандомизирует веса и инициализирует
//   состояния оптимизаторов (Adam, Momentum).
//
// Почему вызывается именно в этом порядке:
//   1. setBias() — bias-нейроны должны быть установлены до рандомизации,
//      потому что они влияют на структуру слоёв и индексацию.
//   2. addWeights() — создаёт матрицы весов нулями (если ещё не созданы).
//      Нужна перед randomizeWeights(), иначе нечего рандомизировать.
//   3. randomizeWeights() — заполняет веса случайными значениями по
//      алгоритму weightInit_ (по умолчанию INIT_HE). Правильная инициализация
//      критически важна: плохие начальные веса приводят к затухающим или
//      взрывающимся градиентам.
//   4. Инициализация Adam/Momentum состояний — создаёт нулевые матрицы
//      для моментов (m, v) и скоростей (velocity). Без этого первый вызов
//      backwardPass() с Adam/Momentum приведёт к обращению к пустым векторам.
//
//   adamState_.t = 0 — счётчик временных шагов Adam. Нужен для bias correction:
//   первые шаги Adam занижены, и t позволяет скорректировать это смещение.
void NeuralNetController::initialize()
{
    setBias();
    addWeights();
    randomizeWeights();

    // Инициализация состояния Adam-оптимизатора
    //
    // Adam хранит два момента для каждого веса:
    //   m — скользящее среднее градиентов (первый момент, «скорость»);
    //   v — скользящее среднее квадратов градиентов (второй момент, «накопление»).
    //
    // Оба момента инициализируются нулями. Счётчик t = 0 — глобальный
    // номер шага, увеличивается после каждого полного backwardPass().
    adamState_.m.clear();
    adamState_.v.clear();
    adamState_.t = 0;
    for (auto &wm : weights_) {
        WeightMatrix m(wm.size(), std::vector<float>(wm[0].size(), 0.0f));
        WeightMatrix v(wm.size(), std::vector<float>(wm[0].size(), 0.0f));
        adamState_.m.push_back(std::move(m));
        adamState_.v.push_back(std::move(v));
    }

    // Инициализация состояния Momentum-оптимизатора
    //
    // Momentum хранит «скорость» (velocity) для каждого веса —
    // экспоненциально убывающую сумму прошлых градиентов:
    //   velocity = momentum * velocity + gradient
    //   weight  -= learningRate * velocity
    //
    // Инициализируется нулями — сеть начинает с «места» без импульса.
    momentumState_.velocity.clear();
    for (auto &wm : weights_) {
        WeightMatrix vel(wm.size(), std::vector<float>(wm[0].size(), 0.0f));
        momentumState_.velocity.push_back(std::move(vel));
    }
}

// --- Добавить слой ---
//
// Назначение:
//   Добавляет новый слой с указанным количеством нейронов в сеть.
//   Слои добавляются последовательно: первый вызов — входной слой,
//   последующие — скрытые и выходной.
//
// Как строится архитектура:
//   Каждый слой — это вектор нейронов (struct Neuron), где каждый нейрон
//   хранит три поля:
//     output — результат после функции активации (или входные данные);
//     error  — локальный градиент (dLoss/dz), вычисленный при обратном проходе;
//     z      — взвешенная сумма входов до применения активации.
//
//   Нейроны инициализируются нулями: {0.0f, 0.0f} — это значит output=0,
//   error=0. Поле z не инициализируется явно (по умолчанию 0.0).
//
//   biasIndices_ заполняется значением -1, что означает «bias-нейрон ещё
//   не установлен». Bias будет добавлен позже через setBias().
//
// Почему выбрасывает исключение при neuronCount <= 0:
//   Слой с нулём или отрицательным количеством нейронов не имеет смысла.
//   Лучше сразу сообщить об ошибке, чем получить странное поведение позже.
//
// Параметры:
//   neuronCount — количество нейронов в новом слое (должно быть > 0).
//
// Пример построения сети 784->30->10:
//   ctrl.addLayer(784);  // layers_[0]: 784 нейрона (входной)
//   ctrl.addLayer(30);   // layers_[1]: 30 нейронов (скрытый)
//   ctrl.addLayer(10);   // layers_[2]: 10 нейронов (выходной)
//   // После этого: layers_.size() == 3, biasIndices_.size() == 3
void NeuralNetController::addLayer(int neuronCount)
{
    if (neuronCount <= 0)
    {
        throw std::invalid_argument("neuronCount must be positive");
    }

    Layer layer(neuronCount, {0.0f, 0.0f});
    layers_.push_back(std::move(layer));
    biasIndices_.push_back(-1);
}

// --- Создать матрицы весов ---
//
// Назначение:
//   Создаёт матрицы весов между всеми соседними слоями.
//   Для N слоёв создаёт N-1 матрицу: weights_[i] соединяет layers_[i]
//   с layers_[i+1].
//
// Как строится архитектура сети:
//   Матрица весов weights_[i] имеет размерность:
//     строки = количество нейронов в layers_[i+1] (выходящие нейроны);
//     столбцы = количество нейронов в layers_[i] (входящие нейроны).
//
//   Индексация: weights_[i][j][k] — вес связи от k-го нейрона слоя i
//   к j-му нейрону слоя i+1.
//
//   Пример для сети 784->30->10:
//     weights_[0]: 30 строк x 784 столбца (входной -> скрытый)
//     weights_[1]: 10 строк x 30 столбцов (скрытый -> выходной)
//
// Почему проверяет layerCount() < 2:
//   Матрица весов нужна только когда есть хотя бы два слоя (один вход,
//   один выход). Для одного слоя создавать нечего.
//
// Почему инициализирует нулями:
//   Нули — безопасное начальное значение. Реальная рандомизация произойдёт
//   позже в randomizeWeights(), которая вызывается из initialize().
//   Разделение «создать нулевые веса» и «рандомизировать» позволяет
//   загрузить веса из файла (loadState) без случайной перезаписи.
//
// Почему вызывает hiddenLayerCount() итераций:
//   hiddenLayerCount() = layerCount() - 1, что равно количеству переходов
//   между слоями (и, соответственно, количеству матриц весов).
//   Для сети 784->30->10: hiddenLayerCount() = 2, цикл выполнится 2 раза.
void NeuralNetController::addWeights()
{
    if (layerCount() < 2)
        return;

    for (int i = 0; i < hiddenLayerCount(); i++)
    {
        int outputNeurons = neuronCount(i + 1);
        int inputNeurons = neuronCount(i);
        weights_.emplace_back(outputNeurons, std::vector<float>(inputNeurons, 0.0f));
    }
}

// --- Установить входные данные ---
//
// Назначение:
//   Копирует значения из массива data в нейроны указанного слоя.
//   Обычно вызывается для входного слоя (layerIndex = 0) перед
//   прямым проходом.
//
// Как данные попадают в сеть:
//   Для каждого элемента data[e] записывается в layers_[layerIndex][e].output.
//   Это «активирует» нейроны входного слоя — они становятся входом для
//   первого прямого прохода.
//
//   После копирования восстанавливается bias-нейрон (если он есть в этом
//   слое): его output = 1.0, error = 0.0. Это нужно, потому что setData()
//   может перезаписать bias-нейрон нулём из data[], а bias должен всегда
//   быть равен 1.0.
//
// Почему использует .at() вместо []:
//   .at() выполняет проверку границ и выбрасывает std::out_of_range при
//   некорректном индексе. Это защищает от ошибок программирования.
//
// Почему проверяет len > layer.size():
//   Если входных данных больше, чем нейронов в слое, часть данных будет
//   потеряна. Лучше выбросить исключение, чем молча проигнорировать данные.
//   Обратная ситуация (len < layer.size()) допустима — оставшиеся нейроны
//   сохранят свои текущие значения.
//
// Параметры:
//   data       — массив входных значений;
//   len        — количество элементов в массиве;
//   layerIndex — индекс целевого слоя (обычно 0 для входного слоя).
void NeuralNetController::setData(const float data[], int len, int layerIndex)
{
    if (layerIndex < 0 || layerIndex >= layerCount())
    {
        throw std::out_of_range("layerIndex out of range");
    }

    auto &layer = layers_.at(layerIndex);
    int biasIdx = biasIndices_.at(layerIndex);

    if (len > static_cast<int>(layer.size()))
    {
        throw std::out_of_range("data length exceeds layer size");
    }

    for (int e = 0; e < len; e++)
    {
        layer[e].output = data[e];
    }

    // Восстанавливаем bias-нейрон: если в слое есть bias-нейрон
    // (biasIdx >= 0), его output всегда должен быть 1.0, а error — 0.0.
    // Это гарантирует, что bias не будет затёрт входными данными.
    if (biasIdx >= 0)
    {
        layer[biasIdx].output = 1.0f;
        layer[biasIdx].error = 0.0f;
    }
}

// --- Установить bias-нейроны ---
//
// Назначение:
//   Для каждого слоя (кроме выходного) устанавливает bias-нейрон —
//   последний нейрон в слое — со значениями output = 1.0, error = 0.0.
//
// Как bias попадает в сеть:
//   Bias-нейрон — это фиктивный нейрон с постоянным выходом 1.0.
//   Он не получает градиент (error = 0.0), но веса, ведущие ОТ него
//   к нейронам следующего слоя, обновляются нормально.
//
//   Математически это эквивалентно свободному члену в линейном уравнении:
//     z = w1*x1 + w2*x2 + ... + wn*xn + b*1.0
//   где b — вес связи от bias-нейрона к нейрону следующего слоя.
//
//   Без bias сеть могла бы проводить разделяющую гиперплоскость только
//   через начало координат, что сильно ограничивает выразительную способность.
//
// Почему именно последний нейрон:
//   Соглашение упрощает код: bias всегда layers_[i].back().
//   biasIndices_ запоминает его позицию для быстрого доступа.
//
// Почему не для выходного слоя:
//   Выходной слой не нуждается в bias-нейроне, потому что его задача —
//   выдавать предсказания, а не передавать сигнал дальше.
//   hiddenLayerCount() = layerCount() - 1, поэтому цикл идёт до
//   предпоследнего слоя включительно.
void NeuralNetController::setBias()
{
    for (int i = 0; i < hiddenLayerCount(); i++)
    {
        int biasIdx = neuronCount(i) - 1;
        layers_[i][biasIdx].output = 1.0f;
        layers_[i][biasIdx].error = 0.0f;
        biasIndices_[i] = biasIdx;
    }
}

// --- Прямое распространение (forward pass) ---
//
// Назначение:
//   Вычисляет активации всех слоёв сети, начиная со второго (индекс 1).
//   После вызова layers_.back()[i].output содержит предсказание сети.
//
// Как проходит прямое распространение по всем слоям:
//   Для каждой пары слоёв (layers_[i] -> layers_[i+1]) с матрицей весов
//   weights_[i] выполняется:
//
//     1. Для каждого нейрона j в выходном слое (layers_[i+1]):
//        z[j] = SUM_k(weights_[i][j][k] * layers_[i][k].output)
//        output[j] = activate(z[j])  // sigmoid, ReLU, Tanh и т.д.
//
//     2. Параметр skipBias указывает индекс bias-нейрона в ЦЕЛЕВОМ слое
//        (layers_[i+1]). Если bias-нейрон есть, он исключается из вычисления
//        градиента, но его входные веса обновляются нормально.
//        Для последнего слоя (выходного) skipBias = -1 (нет bias).
//
//   Порядок: слой за слоем от входного к выходному. Каждый слой получает
//   входные данные от предыдущего и передаёт результат следующему.
//
// Почему skipBias вычисляется условно:
//   biasIndices_.at(i + 1) может быть -1 (если в слое нет bias).
//   Для последнего слоя (i + 1 == layerCount() - 1, т.е. выходной слой)
//   bias-нейрона нет, поэтому skipBias = -1.
//
// Предусловия:
//   Входные данные должны быть установлены через setData() для layers_[0].
//   Bias-нейроны должны быть установлены через setBias().
//   Веса должны быть инициализированы через initialize() или loadState().
void NeuralNetController::forwardPass()
{
    for (int i = 0; i < hiddenLayerCount(); i++)
    {
        int skipBias = (i + 1 < layerCount()) ? biasIndices_.at(i + 1) : -1;
        net_.forwardPass(layers_.at(i), weights_.at(i), layers_.at(i + 1), skipBias);
    }
}

// --- Обратное распространение (backward pass) ---
//
// Назначение:
//   Обновляет веса всех матриц на основе вычисленных градиентов.
//   Движется от выходного слоя к входному (reverse order).
//
// Почему switch по оптимизаторам:
//   Разные оптимизаторы используют разные формулы обновления весов:
//
//   SGD (Stochastic Gradient Descent):
//     w = w - lr * gradient
//     Самый простой, но может медленно сходиться и застревать в локальных минимумах.
//
//   Adam (Adaptive Moment Estimation):
//     m = beta1 * m + (1 - beta1) * gradient       // скользящее среднее градиентов
//     v = beta2 * v + (1 - beta2) * gradient^2     // скользящее среднее квадратов
//     m_hat = m / (1 - beta1^t)                     // bias correction
//     v_hat = v / (1 - beta2^t)                     // bias correction
//     w = w - lr * m_hat / (sqrt(v_hat) + eps)
//     Адаптирует learning rate для каждого веса индивидуально.
//
//   Momentum:
//     velocity = momentum * velocity + gradient
//     w = w - lr * velocity
//     Накопление импульса помогает «проскочить» мелкие локальные минимумы.
//
// Почему t инкрементируется ПОСЛЕ всех обновлений в Adam:
//   Adam использует счётчик шагов t для bias correction.
//   Если инкрементировать t перед каждым обновлением веса, каждый вес
//   получит свой номер шага, что исказит коррекцию смещения.
//   Правильно: все веса обновляются с одним t, затем t++.
//   Это гарантирует, что все веса в рамках одного семпла используют
//   одинаковую коррекцию bias correction.
//
//   Для SGD и Momentum t не нужен — они не используют bias correction.
//
// Порядок обновления:
//   От выходного слоя к входному (i = layerCount()-1 до 1).
//   weights_[i-1] соединяет layers_[i-1] с layers_[i].
void NeuralNetController::backwardPass()
{
    // Примечание: НЕ инкрементируем timestep здесь — Adam сам обрабатывает
    // это внутри, чтобы не считать каждый семпл отдельным шагом для
    // коррекции смещения (bias correction).

    switch (net_.optimizerType) {
        case OPTIMIZER_ADAM:
            for (int i = layerCount() - 1; i >= 1; i--)
            {
                net_.backwardPassAdam(layers_.at(i - 1), weights_.at(i - 1), layers_.at(i),
                                      learningRate_, adamState_.m[i-1], adamState_.v[i-1], adamState_.t);
            }
            adamState_.t++;  // Инкрементируем ПОСЛЕ всех обновлений весов
            break;

        case OPTIMIZER_MOMENTUM:
            for (int i = layerCount() - 1; i >= 1; i--)
            {
                net_.backwardPassMomentum(layers_.at(i - 1), weights_.at(i - 1), layers_.at(i),
                                          learningRate_, momentumState_.velocity[i-1]);
            }
            break;

        case OPTIMIZER_SGD:
        default:
            for (int i = layerCount() - 1; i >= 1; i--)
            {
                net_.backwardPass(layers_.at(i - 1), weights_.at(i - 1), layers_.at(i), learningRate_);
            }
            break;
    }
}

// --- Получить общую ошибку сети ---
//
// Назначение:
//   Вычисляет суммарную ошибку сети как сумму квадратов ошибок
//   выходного слоя.
//
// Как получить результат:
//   Ошибка вычисляется после setOutputError() и computeErrors().
//   Для каждого нейрона выходного слоя берётся его error (разница между
//   предсказанием и целевым значением) и возводится в квадрат.
//
//   error = SUM_i(error[i] ^ 2)
//
//   Это не MSE (mean squared error), а SSE (sum of squared errors) —
//   среднее не делится на количество нейронов. Для сравнения качества
//   это не важно (пропорционально), но абсолютное значение будет больше.
//
// Возвращаемое значение:
//   Сумма квадратов ошибок выходного слоя. Чем меньше, тем лучше.
//   0.0 означает идеальное предсказание (все error[i] = 0).
//
// Почему не выбрасывает исключение при пустом layers_:
//   Возврат 0.0f — безопасное значение. Пустая сеть не может иметь ошибку,
//   и это лучше, чем краш программы.
float NeuralNetController::getError() const
{
    if (layers_.empty())
        return 0.0f;

    const auto &outLayer = layers_.back();
    float error = 0.0f;
    for (const auto &neuron : outLayer)
    {
        error += square(neuron.error);
    }
    return error;
}

// --- Вычислить ошибки для всех слоёв ---
//
// Назначение:
//   Propagates ошибку от выходного слоя к входному через все скрытые слои.
//   Это необходимо для backwardPass(), который использует ошибки нейронов
//   для вычисления градиентов.
//
// Как работает обратное распространение ошибок:
//   Начиная с предпоследнего слоя (скрытые слои + входной) и двигаясь
//   к началу:
//
//     Для слоя i:
//       error_in[k] = SUM_j(error_out[j] * weight[j][k]) * activation'(z[k])
//
//   где:
//     error_out[j] — ошибка j-го нейрона следующего слоя (layers_[i+1]);
//     weight[j][k] — вес связи от k-го нейрона слоя i к j-му нейрону слоя i+1;
//     activation'(z[k]) — производная функции активации в точке z[k].
//
//   Это прямое применение chain rule (цепного правила) из матанализа:
//     dLoss/dz_in = SUM_j(dLoss/dz_out * dz_out/dz_in)
//
// Почему вызывается после setOutputError():
//   setOutputError() устанавливает ошибку только для ВЫХОДНОГО слоя.
//   computeErrors() propagates эту ошибку назад через все скрытые слои.
//   Без computeErrors() ошибки скрытых слоёв будут нулевыми, и
//   backwardPass() не сможет правильно обновить веса.
void NeuralNetController::computeErrors()
{
    for (int i = hiddenLayerCount() - 1; i >= 0; i--)
    {
        net_.computeError(layers_.at(i), weights_.at(i), layers_.at(i + 1), layers_.at(i));
    }
}

