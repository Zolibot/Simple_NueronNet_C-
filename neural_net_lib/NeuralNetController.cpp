// --- Конструктор по умолчанию ---
//
// Назначение:
//   Создаёт пустой контроллер нейронной сети с заданной скоростью обучения.
//   После вызова контроллер не содержит ни слоёв, ни весов — их нужно
//   добавить вручную через addLayer(), addWeights(), initialize().
//
// Почему так реализован:
//   Минимальный конструктор даёт гибкость: пользователь сам определяет
//   архитектуру сети. Список слоёв и весов остаётся пустым, а
//   learningRate_ инициализируется переданным значением.
//
// Параметры:
//   learningRate — скорость обучения (learning rate). Определяет размер
//   шага при обновлении весов: w_new = w_old - lr * gradient.
//   Типичные значения: 0.001 (медленно, точно) — 1.0 (быстро, грубо).
//
// Пример использования:
//   NeuralNetController ctrl(0.5f);
//   ctrl.addLayer(784);   // входной слой (пиксели MNIST 28x28)
//   ctrl.addLayer(30);    // скрытый слой
//   ctrl.addLayer(10);    // выходной слой (цифры 0-9)
//   ctrl.addWeights();    // создать матрицы весов между слоями
//   ctrl.initialize();    // рандомизировать веса, установить bias
NeuralNetController::NeuralNetController(float learningRate)
    : learningRate_(learningRate)
{
}

// --- Конструктор из сохранённого состояния ---
//
// Назначение:
//   Восстанавливает ранее сохранённую сеть из сериализованного состояния.
//   Позволяет продолжить обучение с того места, где оно было остановлено,
//   или использовать обученную сеть для предсказаний.
//
// Чем отличается от первого конструктора:
//   Первый конструктор создаёт пустой контроллер — архитектуру нужно
//   строить с нуля. Этот конструктор сразу восстанавливает слои и веса
//   из savedState через вызов loadState().
//
// Почему так реализован:
//   Делегирует всю логику восстановления методу loadState(), чтобы не
//   дублировать код. learningRate_ можно задать новый — это полезно,
//   если при дообучении нужна другая скорость.
//
// Параметры:
//   savedState   — вектор строк, полученный ранее через saveState().
//                  Первая строка содержит размеры всех слоёв,
//                  остальные строки — веса матриц (по столбцам).
//   learningRate — скорость обучения (можно изменить при загрузке).
//
// Формат savedState (подробности в loadState):
//   Строка 0: "784 31 10 " — размеры слоёв через пробел
//   Строка 1..N: веса по одному столбцу на строку
NeuralNetController::NeuralNetController(const std::vector<std::string> &savedState, float learningRate)
    : learningRate_(learningRate)
{
    loadState(savedState);
}

