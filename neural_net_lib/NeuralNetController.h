#pragma once

#include <string>
#include <vector>
#include <iostream>
#include <sstream>

#include "NeuralNet.h"

// ============================================================================
// NeuralNetController — высокоуровневый управляющий класс нейронной сети
// ============================================================================
//
// Зачем нужен этот класс, если уже есть NeuralNet?
//
//   NeuralNet — это «stateless-ядро»: набор чистых математических операций
//   (прямой проход, обратный проход, инициализация весов, функции активации).
//   Он не знает об архитектуре конкретной сети — просто принимает структуры
//   Layer и WeightMatrix и выполняет над ними вычисления. Один экземпляр
//   NeuralNet можно переиспользовать для множества разных сетей.
//
//   NeuralNetController — это «stateful-оболочка», которая хранит:
//     • архитектуру сети (сколько слоёв, сколько нейронов в каждом);
//     • текущие значения весов и bias;
//     • состояние оптимизаторов (Adam, Momentum);
//     • гиперпараметры (learning rate, decay, тип инициализации).
//
//   Такое разделение отвечает принципу single responsibility:
//     • NeuralNet — «как считать» (математика);
//     • NeuralNetController — «что считать» (архитектура + состояние).
//
// Архитектура сети в контроллере:
//
//   Сеть состоит из последовательности слоёв: входной → скрытые → выходной.
//   Каждый слой — это вектор нейронов (структура Neuron с полями output,
//   error, z). Между каждыми двумя соседними слоями лежит матрица весов
//   WeightMatrix, где weN[j][i] — вес связи от i-го нейрона предыдущего
//   слоя к j-му нейрону текущего слоя.
//
//   Пример для сети 784→30→10 (MNIST):
//     layers_[0] — входной слой: 784 нейрона (пиксели изображения)
//     layers_[1] — скрытый слой: 30 нейронов
//     layers_[2] — выходной слой: 10 нейронов (цифры 0–9)
//     weights_[0] — матрица 30×784 (входной → скрытый)
//     weights_[1] — матрица 10×30 (скрытый → выходной)
//
// Bias-нейрон:
//
//   В каждом слое (кроме, возможно, входного) последний нейрон — это
//   bias-нейрон. Его output всегда равен 1.0, а error всегда равен 0.0.
//   Зачем? Bias — это свободный член в линейном уравнении нейрона:
//
//     z = w1*x1 + w2*x2 + ... + wn*xn + b
//
//   Вместо того чтобы хранить b отдельно, мы добавляем фиктивный вход
//   со значением 1.0 и связываем его с весом b. Тогда:
//
//     z = w1*x1 + w2*x2 + ... + wn*xn + b*1.0
//
//   Это упрощает код: bias обрабатывается как обычный вес, и не нужно
//   писать отдельную логику для его обновления. Bias-нейрон не получает
//   градиент (error = 0.0), но веса, ведущие К нему, обновляются нормально.
//
// Почему AdamState и MomentumState хранятся в контроллере, а не в NeuralNet?
//
//   Состояние оптимизатора (моменты, скорости) привязано к КОНКРЕТНОЙ сети
//   с конкретными весами. Если бы мы хранили его в NeuralNet, то при
//   переиспользовании одного экземпляра NeuralNet для разных сетей состояния
//   смешались бы. Кроме того, NeuralNet задуман как stateless-утилита —
//   добавление туда stateful-полей нарушило бы эту абстракцию.
//
//   Контроллер — естественное место для состояния оптимизатора, потому что
//   он уже хранит веса сети. Оптимизатор и веса — две стороны одной медали:
//   веса — это «где мы сейчас», состояние оптимизатора — «куда мы движемся».
//
class NeuralNetController {
private:
    // =========================================================================
    // Приватные поля
    // =========================================================================

    /// Все слои сети в порядке от входного к выходному.
    ///
    /// layers_[0] — всегда входной слой (активации входных данных).
    /// layers_[1..N-2] — скрытые слои (если есть).
    /// layers_[N-1] — выходной слой (предсказания сети).
    ///
    /// Каждый слой — вектор нейронов (Neuron), где каждый нейрон хранит:
    ///   output — результат после функции активации;
    ///   error  — локальный градиент (dLoss/dz);
    ///   z      — взвешенная сумма входов до активации.
    ///
    /// Последний нейрон в каждом слое (кроме входного) — bias-нейрон
    /// с output = 1.0 и error = 0.0.
    std::vector<Layer> layers_;

    /// Матрицы весов между соседними слоями.
    ///
    /// weights_[i] — матрица весов от layers_[i] к layers_[i+1].
    /// Индексация: weights_[i][выходящий_нейрон][входящий_нейрон].
    ///
    /// Для сети с N слоями (layers_.size() == N) всегда N-1 матрица весов.
    /// Размер матрицы weights_[i]: layers_[i+1].size() × layers_[i].size().
    std::vector<WeightMatrix> weights_;

    /// Индексы bias-нейронов в каждом слое.
    ///
    /// biasIndices_[i] — индекс последнего нейрона в layers_[i], который
    /// является bias-нейроном (output = 1.0, error = 0.0).
    ///
    /// Значение -1 означает, что в данном слое нет bias-нейрона
    /// (обычно это входной слой, куда данные подаются извне).
    ///
    /// Хранение индексов вместо жёсткого «последний элемент» позволяет
    /// в будущем изменить расположение bias без переписывания логики.
    std::vector<int> biasIndices_;

    /// Ядро нейронной сети — stateless-утилита для математических операций.
    ///
    /// Содержит функции активации, их производные, методы прямого и обратного
    /// прохода, инициализации весов. Не хранит архитектуру сети — работает
    /// с переданными структурами Layer и WeightMatrix.
    ///
    /// Также хранит настройки: тип активации, тип оптимизатора, параметры
    /// Adam/Beta, флаги dropout и batch normalization.
    NeuralNet net_;

    /// Скорость обучения (learning rate).
    ///
    /// Определяет размер шага при обновлении весов:
    ///   w_new = w_old - learningRate * gradient
    ///
    /// Слишком большое значение — сеть «перескакивает» минимум.
    /// Слишком маленькое — обучение идёт очень медленно.
    /// Типичные значения: 0.001 – 1.0.
    float learningRate_;

    /// Скорость затухания learning rate (learning rate decay).
    ///
    /// Позволяет автоматически уменьшать learning rate с ростом эпохи:
    ///   effective_lr = learningRate_ / (1 + learningRateDecay_ * currentEpoch_)
    ///
    /// Это помогает сети точнее сойтись к минимуму: в начале обучения
    /// большие шаги быстро приближают к решению, а к концу маленькие
    /// шаги позволяют «войти» в минимум без перелёта.
    ///
    /// Значение 0.0 означает отсутствие затухания (learning rate постоянен).
    float learningRateDecay_ = 0.0f;

    /// Текущий номер эпохи (для learning rate decay).
    ///
    /// Инкрементируется после каждой полной итерации обучения по всем
    /// тренировочным данным. Используется в формуле затухания.
    int currentEpoch_ = 0;

    /// Тип инициализации весов по умолчанию.
    ///
    /// Определяет, каким алгоритмом будут заполнены начальные веса:
    ///   INIT_UNIFORM   — равномерное распределение [-weightRange, +weightRange];
    ///   INIT_XAVIER    — дисперсия 2/(n_in + n_out), хорошо для sigmoid/Tanh;
    ///   INIT_HE        — дисперсия 2/n_in, хорошо для ReLU/Leaky ReLU.
    ///
    /// Правильная инициализация критически важна: плохие начальные веса
    /// приводят к затухающим или взрывающимся градиентам.
    WeightInit weightInit_ = INIT_HE;

    /// Состояние Adam-оптимизатора.
    ///
    /// Adam (Adaptive Moment Estimation) для каждого веса хранит:
    ///   m — скользящее среднее градиентов (первый момент, «скорость»);
    ///   v — скользящее среднее квадратов градиентов (второй момент, «накопление»).
    ///
    /// Каждый элемент вектора соответствует одной матрице из weights_.
    /// Поле t — глобальный счётчик шагов для коррекции смещения (bias correction).
    ///
    /// Хранится здесь, а не в NeuralNet, потому что состояние привязано
    /// к конкретной сети (её весам), а NeuralNet — stateless-утилита.
    AdamState adamState_;

    /// Состояние Momentum-оптимизатора.
    ///
    /// Momentum для каждого веса хранит «скорость» (velocity) —
    /// экспоненциально убывающую сумму прошлых градиентов:
    ///   velocity = momentum * velocity + gradient
    ///   weight  -= learningRate * velocity
    ///
    /// Каждый элемент вектора соответствует одной матрице из weights_.
    ///
    /// Хранится здесь по той же причине, что и adamState_: состояние
    /// привязано к конкретной сети, а не к математическому ядру.
    MomentumState momentumState_;

public:
    // =========================================================================
    // Конструкторы и деструктор
    // =========================================================================

    /// Основной конструктор: создаёт пустой контроллер с заданной скоростью обучения.
    ///
    /// После создания контроллер не содержит слоёв и весов.
    /// Необходимо вызвать addLayer() для добавления слоёв, затем
    /// addWeights() для создания матриц весов, и initialize() для
    /// рандомизации весов и установки bias.
    ///
    /// Пример:
    ///   NeuralNetController controller(0.5f);
    ///   controller.addLayer(784);  // входной
    ///   controller.addLayer(30);   // скрытый
    ///   controller.addLayer(10);   // выходной
    ///   controller.addWeights();
    ///   controller.initialize();
    ///
    /// @param learningRate  Скорость обучения (типичные значения: 0.001–1.0)
    explicit NeuralNetController(float learningRate);

    /// Конструктор из сохранённого состояния: восстанавливает архитектуру и веса.
    ///
    /// Позволяет загрузить ранее сохранённую сеть (через saveState()) и
    /// продолжить обучение или использовать для предсказаний.
    ///
    /// Формат savedState: вектор строк, где каждая строка содержит
    /// закодированные веса матриц и структуру слоёв.
    ///
    /// @param savedState    Вектор строк с сохранённым состоянием сети
    /// @param learningRate  Скорость обучения (можно изменить при загрузке)
    NeuralNetController(const std::vector<std::string> &savedState, float learningRate);

    /// Деструктор по умолчанию.
    ///
    /// Все ресурсы (векторы) освобождаются автоматически.
    ~NeuralNetController() = default;

    // Запрещаем копирование (Rule of Five): владение ресурсами (весами,
    /// состоянием оптимизатора) не должно дублироваться. Случайное копирование
    /// могло бы привести к рассинхронизации весов и состояния оптимизатора.
    NeuralNetController(const NeuralNetController &) = delete;
    NeuralNetController &operator=(const NeuralNetController &) = delete;

    /// Разрешаем перемещение (move semantics): эффективная передача владения
    /// без глубокого копирования больших матриц весов.
    NeuralNetController(NeuralNetController &&) = default;
    NeuralNetController &operator=(NeuralNetController &&) = default;

    // =========================================================================
    // Утилиты
    // =========================================================================

    /// Квадрат числа: возвращает n * n.
    ///
    /// Вспомогательная функция для вычисления ошибки (MSE = mean squared error).
    /// Объявлена static, потому что не зависит от состояния объекта.
    ///
    /// @param n  Число для возведения в квадрат
    /// @return   n * n
    static float square(float n);

    /// Инвертирует все веса сети (умножает на -1).
    ///
    /// Тестовая функция: используется для проверки корректности загрузки/
    /// сохранения и отладки. Не имеет практического смысла в обучении.
    void reverseWeights();

    // =========================================================================
    // Обучение
    // =========================================================================

    /// Обучение сети: классификация (целевое значение — номер класса).
    ///
    /// Выполняет полный цикл обучения на одном примере:
    ///   1. Устанавливает входные данные (должны быть заданы через setData);
    ///   2. Прямой проход (forwardPass);
    ///   3. Вычисляет ошибку выходного слоя для заданного класса;
    ///   4. Обратный проход (backwardPass) — обновление весов.
    ///
    /// Целевой класс кодируется номером нейрона в выходном слое.
    /// Например, targetClass = 3 означает, что 4-й нейрон выходного слоя
    /// должен выдать 1.0, а все остальные — 0.0.
    ///
    /// @param targetClass  Номер целевого класса (индекс нейрона в выходном слое)
    void train(int targetClass);

    /// Обучение сети: регрессия (целевое значение — массив непрерывных значений).
    ///
    /// Аналогичен train(int), но вместо класса принимает массив целевых
    /// значений для каждого нейрона выходного слоя.
    ///
    /// Используется для задач регрессии, где ответ — не дискретный класс,
    /// а непрерывное значение (например, предсказание цены, температуры).
    ///
    /// @param targets  Массив целевых значений (длина = размер выходного слоя)
    void train(const float targets[]);

    /// Обучение мини-батчем: обработка нескольких примеров перед обновлением весов.
    ///
    /// Мини-батч даёт более стабильный градиент (усреднение шума) и лучшее
    /// использование процессора. Алгоритм:
    ///   1. Для каждого примера: forwardPass + вычисление градиентов;
    ///   2. Накопление градиентов в аккумулятор;
    ///   3. Усреднение градиентов по размеру батча;
    ///   4. Обновление весов усреднённым градиентом.
    ///
    /// @param inputs   Вектор входных примеров (каждый пример — вектор float)
    /// @param targets  Вектор целевых значений (каждый target — вектор float)
    void trainMiniBatch(const std::vector<std::vector<float>> &inputs,
                        const std::vector<std::vector<float>> &targets);

    /// Обучение с Adam-оптимизатором.
    ///
    /// Использует Adam вместо обычного SGD для обновления весов.
    /// Adam адаптирует learning rate для каждого веса индивидуально на основе
    /// скользящих средних градиента и его квадрата.
    ///
    /// @param targets  Массив целевых значений (длина = размер выходного слоя)
    void trainAdam(const float targets[]);

    // =========================================================================
    // Настройка сети (гиперпараметры)
    // =========================================================================

    /// Установить тип инициализации весов.
    ///
    /// Влияет на поведение initialize() и randomizeWeights().
    /// Должен вызываться ДО initialize().
    ///
    /// @param init  Тип инициализации: INIT_UNIFORM, INIT_XAVIER, INIT_HE
    void setWeightInit(WeightInit init) { weightInit_ = init; }

    /// Установить тип функции активации для всей сети.
    ///
    /// Активация применяется ко всем нейронам (кроме bias) при прямом проходе.
    /// Тип влияет на производную при обратном проходе и на выбор инициализации.
    ///
    /// @param type  Тип активации: ACTIVATION_SIGMOID, ACTIVATION_RELU,
    ///              ACTIVATION_LEAKY_RELU, ACTIVATION_TANH
    void setActivation(ActivationType type) { net_.activationType = type; }

    /// Установить тип оптимизатора для обновления весов.
    ///
    /// Определяет, какой алгоритм будет использоваться в backwardPass().
    /// OPTIMIZER_SGD — обычный градиентный спуск;
    /// OPTIMIZER_ADAM — требует вызова trainAdam() или настройки backwardPass;
    /// OPTIMIZER_MOMENTUM — SGD с импульсом.
    ///
    /// @param type  Тип оптимизатора: OPTIMIZER_SGD, OPTIMIZER_ADAM, OPTIMIZER_MOMENTUM
    void setOptimizer(OptimizerType type) { net_.optimizerType = type; }

    /// Установить dropout — технику регуляризации.
    ///
    /// Dropout случайно «выключает» часть нейронов при каждом прямом проходе,
    /// предотвращая переобучение (co-adaptation). Выключенные нейроны не
    /// участвуют в прямом проходе и не получают градиент при обратном.
    ///
    /// При rate = 0.0 dropout отключён. При rate = 0.5 каждый нейрон имеет
    /// 50% шанс быть выключенным.
    ///
    /// ВАЖНО: dropout применяется только при обучении. При инференсе
    /// (predict) все нейроны активны, а выходы масштабируются на (1 - rate).
    ///
    /// @param rate  Вероятность выключения нейрона (0.0 — выключено, 0.5 — типично)
    void setDropout(float rate) { net_.useDropout = (rate > 0.0f); net_.dropoutRate = rate; }

    /// Включить или выключить Batch Normalization.
    ///
    /// BatchNorm нормализует выходы каждого слоя к нулевому среднему и
    /// единичной дисперсии внутри мини-батча, затем применяет обучаемые
    /// параметры gamma (масштаб) и beta (сдвиг).
    ///
    /// Преимущества:
    ///   • Ускоряет обучение (можно использовать больший learning rate);
    ///   • Уменьшает чувствительность к начальной инициализации;
    ///   • Действует как лёгкий регуляризатор.
    ///
    /// @param enable  true — включить, false — выключить
    void setBatchNorm(bool enable) { net_.useBatchNorm = enable; }

    /// Установить затухание learning rate.
    ///
    /// Learning rate уменьшается с каждой эпохой по формуле:
    ///   effective_lr = learningRate_ / (1 + decay * currentEpoch_)
    ///
    /// @param decay  Коэффициент затухания (0.0 — без затухания)
    void setLearningRateDecay(float decay) { learningRateDecay_ = decay; }

    // =========================================================================
    // Построение архитектуры
    // =========================================================================

    /// Добавить слой с указанным количеством нейронов.
    ///
    /// Слои добавляются последовательно: первый вызов создаёт входной слой,
    /// последующие — скрытые и выходной. Количество слоёв не ограничено.
    ///
    /// После добавления всех слоёв необходимо вызвать addWeights() для
    /// создания матриц весов между ними.
    ///
    /// Пример для сети 784→30→10:
    ///   addLayer(784);  // входной: 784 нейрона (пиксели 28×28)
    ///   addLayer(30);   // скрытый: 30 нейронов
    ///   addLayer(10);   // выходной: 10 нейронов (цифры 0–9)
    ///
    /// @param neuronCount  Количество нейронов в новом слое
    void addLayer(int neuronCount);

    /// Создать матрицы весов между всеми соседними слоями.
    ///
    /// Для N слоёв создаёт N-1 матрицу весов:
    ///   weights_[0] — от layers_[0] к layers_[1]
    ///   weights_[1] — от layers_[1] к layers_[2]
    ///   ...
    ///
    /// Размер матрицы weights_[i]: layers_[i+1].size() × layers_[i].size().
    ///
    /// Должна вызываться ПОСЛЕ добавления всех слоёв (addLayer) и
    /// ДО инициализации (initialize).
    void addWeights();

    // =========================================================================
    // Инициализация
    // =========================================================================

    /// Полная инициализация сети: bias-нейроны + рандомизация весов.
    ///
    /// Выполняет два шага:
    ///   1. setBias() — добавляет bias-нейрон (output=1.0, error=0.0)
    ///      в каждый слой (кроме входного);
    ///   2. randomizeWeights() — заполняет все матрицы весов случайными
    ///      значениями согласно текущему типу инициализации (weightInit_).
    ///
    /// Должна вызываться после addWeights() и перед началом обучения.
    void initialize();

    // =========================================================================
    // Установка данных
    // =========================================================================

    /// Установить входные данные для указанного слоя.
    ///
    /// Копирует значения из массива data в нейроны слоя layerIndex.
    /// Обычно вызывается для входного слоя (layerIndex = 0) перед
    /// прямым проходом.
    ///
    /// Для каждого нейрона i: layers_[layerIndex][i].output = data[i]
    ///
    /// @param data        Массив входных значений
    /// @param len         Длина массива (должна равняться количеству нейронов)
    /// @param layerIndex  Индекс целевого слоя (обычно 0 — входной)
    void setData(const float data[], int len, int layerIndex);

    /// Установить bias-нейроны во всех слоях (кроме входного).
    ///
    /// Для каждого слоя (начиная со второго) добавляет один дополнительный
    /// нейрон со значениями:
    ///   output = 1.0  (фиксированное значение — «единичный вход»)
    ///   error  = 0.0  (bias не получает градиент)
    ///   z      = 1.0  (pre-activation = output для bias)
    ///
    /// Bias-нейрон позволяет сети смещать функцию активации, что критически
    /// важно для обучения. Без bias сеть могла бы проводить разделяющую
    /// гиперплоскость только через начало координат.
    ///
    /// Обновляет biasIndices_ — запоминает индекс добавленного нейрона.
    void setBias();

    // =========================================================================
    // Прямой и обратный проход
    // =========================================================================

    /// Прямое распространение (forward pass) по всей сети.
    ///
    /// Последовательно вычисляет активации каждого слоя, начиная со
    /// второго (индекс 1). Для каждой пары слоёв (in → out):
    ///   1. Для каждого нейрона j в выходном слое:
    ///      z[j] = sum_i(weights[j][i] * in[i].output) + bias[j]
    ///   2. output[j] = activate(z[j])
    ///
    /// Результат: после вызова layers_.back()[i].output содержит
    /// предсказание сети для i-го выходного нейрона.
    void forwardPass();

    /// Обратное распространение (backward pass) по всей сети.
    ///
    /// Последовательно обновляет веса, двигаясь от выходного слоя к входному.
    /// Для каждой пары слоёв (in → out) с матрицей весов weights_[i]:
    ///   1. Вычисляет градиенты: gradient[j][i] = error_out[j] * output_in[i]
    ///   2. Обновляет веса: weights_[i][j][i] -= lr * gradient[j][i]
    ///   3. Propagates error обратно: error_in[i] = sum_j(error_out[j] * weight[j][i])
    ///
    /// ВАЖНО: перед вызовом backwardPass должны быть:
    ///   • Выполнены forwardPass (для вычисления output);
    ///   • Установлена ошибка выходного слоя (setOutputError или train).
    void backwardPass();

    /// Вычислить ошибки (градиенты) для всех слоёв сети.
    ///
    /// Обратный проход ошибок: начиная с выходного слоя (где ошибка уже
    /// установлена), propagates error назад через каждый слой:
    ///   error_in[i] = sum_j(error_out[j] * weight[j][i])
    ///
    /// Это необходимо для backwardPass, который использует ошибки для
    /// обновления весов.
    void computeErrors();

    // =========================================================================
    // Предсказание и ошибка
    // =========================================================================

    /// Предсказание класса по выходу сети.
    ///
    /// Находит нейрон с максимальным output в выходном слое и возвращает
    /// его индекс. Это предсказанный класс.
    ///
    /// Перед вызовом должен быть выполнен forwardPass.
    ///
    /// Пример: если layers_.back() = [0.1, 0.8, 0.05, 0.05], вернёт 1.
    ///
    /// @return  Индекс нейрона с максимальной активацией
    int predict() const;

    /// Получить общую ошибку сети (сумма квадратов ошибок выходного слоя).
    ///
    /// Вычисляется как MSE (mean squared error):
    ///   error = sum_i(output_error[i] ^ 2)
    ///
    /// где output_error[i] — разница между предсказанием и целевым значением
    /// для i-го нейрона выходного слоя.
    ///
    /// @return  Сумма квадратов ошибок (чем меньше, тем лучше)
    float getError() const;

    // =========================================================================
    /// Ошибка выходного слоя: классификация (one-hot encoding).
    ///
    /// Устанавливает ошибку для каждого нейрона выходного слоя на основе
    /// целевого класса. Используется one-hot encoding: целевой нейрон должен
    /// выдать 1.0, все остальные — 0.0.
    ///
    /// Формула для каждого нейрона i:
    ///   target[i] = (i == targetClass) ? 1.0 : 0.0
    ///   error[i]  = (output[i] - target[i]) * activation_derivative(z[i])
    ///
    /// @param targetClass  Номер целевого класса (индекс нейрона)
    void setOutputError(int targetClass);

    /// Ошибка выходного слоя: регрессия (непрерывные значения).
    ///
    /// Аналогичен setOutputError(int), но принимает массив целевых значений
    /// вместо номера класса.
    ///
    /// @param targets  Массив целевых значений (длина = размер выходного слоя)
    void setOutputError(const float targets[]);

    // =========================================================================
    // Веса
    // =========================================================================

    /// Рандомизировать все веса сети согласно текущему типу инициализации.
    ///
    /// Вызывает net_.randomizeWeights() для каждой матрицы весов.
    /// Тип инициализации определяется weightInit_ (по умолчанию INIT_HE).
    ///
    /// Должна вызываться после addWeights() и перед началом обучения.
    /// Повторный вызов полностью сбрасывает веса (полезно для перезапуска).
    void randomizeWeights();

    // =========================================================================
    // Сохранение и загрузка
    // =========================================================================

    /// Сохранить состояние сети в вектор строк.
    ///
    /// Сериализует:
    ///   • Количество слоёв и количество нейронов в каждом;
    ///   • Все матрицы весов (полностью, построчно);
    ///   • Индексы bias-нейронов.
    ///
    /// Формат: каждая строка содержит одну порцию данных.
    /// Строки можно записать в файл и позже восстановить через loadState().
    ///
    /// @return  Вектор строк с закодированным состоянием
    std::vector<std::string> saveState() const;

    /// Загрузить состояние сети из вектора строк.
    ///
    /// Восстанавливает:
    ///   • Архитектуру слоёв (количество и размеры);
    ///   • Матрицы весов (значения);
    ///   • Индексы bias-нейронов.
    ///
    /// После загрузки сеть готова к обучению или предсказанию.
    /// Оптимизаторы (Adam, Momentum) сбрасываются — продолжение обучения
    /// начнётся с «чистого» состояния оптимизатора.
    ///
    /// @param savedState  Вектор строк, ранее полученный через saveState()
    void loadState(const std::vector<std::string> &savedState);

    // =========================================================================
    // Аксессоры
    // =========================================================================

    /// Получить слой по индексу (const-версия).
    ///
    /// Позволяет читать данные слоя без модификации.
    ///
    /// @param index  Индекс слоя (0 — входной, N-1 — выходной)
    /// @return       Const-ссылка на слой
    const Layer &getLayer(int index) const;

    /// Получить слой по индексу (не-const-версия).
    ///
    /// Позволяет модифицировать данные слоя (например, установить входные
    /// данные вручную).
    ///
    /// @param index  Индекс слоя (0 — входной, N-1 — выходной)
    /// @return       Ссылка на слой
    Layer &getLayer(int index);

    /// Общее количество слоёв в сети (включая входной и выходной).
    ///
    /// Для сети 784→30→10 вернёт 3.
    ///
    /// @return  Количество слоёв
    int layerCount() const { return static_cast<int>(layers_.size()); }

    /// Количество нейронов в указанном слое (включая bias-нейрон).
    ///
    /// Если в слое есть bias-нейрон, он учитывается в количестве.
    /// Например, для скрытого слоя с 30 «рабочими» нейронами и 1 bias
    /// вернёт 31.
    ///
    /// @param layerIndex  Индекс слоя
    /// @return            Количество нейронов
    int neuronCount(int layerIndex) const { return static_cast<int>(layers_.at(layerIndex).size()); }

    /// Количество скрытых слоёв (без учёта выходного).
    ///
    /// Для сети 784→30→10 вернёт 2 (входной + 1 скрытый = 3 слоя всего,
    /// минус 1 выходной = 2).
    ///
    /// Формула: layerCount() - 1.
    ///
    /// @return  Количество скрытых слоёв
    int hiddenLayerCount() const { return layerCount() - 1; }
};
